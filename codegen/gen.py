        self.shape = None
        self.enc = None
        self.kind = None
        self.is_class = decl.is_class
        self.skip = None
        self.reason = None
        self.java_name = None
        self.field = None
        self.handle = None
        self.params = []
        self.ret_kind = None
        self.renamed_from = None
        self.guards = []
        self.guard_setup = []
        self.nil_skips = []
        self.nil_returns = {}
        self.class_consts = []
        self.is_constructor = False
