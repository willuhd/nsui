def resolve_inherited_names(plans, effective, superclass):
    """Apply every inherited-signature decision to `plans` in place, returning report lines.

    Shared with the tooling (codegen/probe.py enumerates calls from the plans), because a caller
    that plans a class on its own has to see the same Java names the generator will emit —
    otherwise it synthesizes calls to methods that were renamed or skipped.
    """
    notes = []
    inherited = inherited_members(effective, superclass)
    used_names = {q.java_name for q in plans if not q.skip}
    for q in plans:
        if q.skip:
            continue
        forms = [f for f in inherited.get(q.java_name, []) if f[0] == len(q.params)]
        if not forms:
            continue
        is_static, ret = forms[0][1], forms[0][2]
        note = None
        renamed = False
        if is_static == q.is_class:
            # The target tree already provides this member on an ancestor, so emitting it again
            # would only duplicate an inherited API. This is the general replacement for the old
            # per-name blacklist of hash/copy/description/isKindOfClass: and friends.
            q.skip = True
            q.reason = "already provided by an inherited wrapper"
            note = "SKIP %s  [inherited from a shipped wrapper]" % q.java_name
        elif is_static != q.is_class:
            before = q.java_name
            q.java_name += "Class" if q.is_class else "Instance"
            renamed = True
            note = "RENAMED %s -> %s   [static/instance clash with an inherited member]" % (
                before, q.java_name)
        elif ret != q.ret_java:
            if ret == "MemorySegment":
                q.ret_kind, before = "id", q.ret_java
                q.ret_java = ret
                note = "RETYPED %s: %s -> MemorySegment   [inherited signature wins]" % (
                    q.java_name, before)
            elif ret in effective:
                q.ret_kind, before = "typed", q.ret_java
                q.ret_java = ret
                note = "RETYPED %s: %s -> %s   [inherited signature wins]" % (
                    q.java_name, before, ret)
            else:
                before = q.java_name
                q.java_name += "Own"
                renamed = True
                note = "RENAMED %s -> %s   [return type differs from the inherited member]" % (
                    before, q.java_name)
        if note:
            if renamed:
                while q.java_name in used_names:
                    q.java_name += "_"
                used_names.add(q.java_name)
            notes.append(note)
    return notes


def plan_class(cls, frameworks, sdk, vocab, wrappers, rt, toolkit=None, include_deprecated=True):
    """Everything the generator decides for one class, in one place.

    Tools that need the same view (probe.py enumerating calls, a future conformance checker) get
    the post-rename plans this way instead of re-deriving the naming rules.
    """
    surface = collect_surface(cls, frameworks, sdk)
    if surface is None:
        return None
    effective = dict(wrappers)
    superclass = surface.superclass if surface.superclass in effective else "NSObject"
    plans = build_plan(surface, rt, vocab, effective, cls, include_deprecated=include_deprecated,
                       toolkit=toolkit)
    notes = resolve_inherited_names(plans, effective, superclass)
    return {"surface": surface, "superclass": superclass, "plans": plans, "notes": notes,
            "effective": effective}


def gen_classes(args, sdk, vocab, wrappers, rt):
    files = []
    lines = []
    new_shape_counter = {}
    vocab_needed = []
    protected_init = subclasses_using_init(wrappers)
    toolkit = Toolkit(getattr(args, "repo", "."))
    evidence, evidence_path = load_guard_evidence(getattr(args, "guard_evidence", None))
    shipped_verdicts = load_shipped_baseline(getattr(args, "shipped_baseline", None))
    if evidence:
        lines.append("NOTE guard evidence: %s (%d case(s))"
                     % (os.path.basename(evidence_path),
                        sum(len(v) for v in evidence.values())))
    missing_primitives = toolkit.missing()
    if missing_primitives:
        lines.append("NOTE target tree lacks: %s" % ", ".join(missing_primitives))
    surfaces = OrderedDict()
    for cls in args.classes:
        surface = collect_surface(cls, args.frameworks, sdk)
        if surface is None:
            lines.append("SKIP %s: no @interface in %s" % (cls, ", ".join(args.frameworks)))
            continue
        surfaces[cls] = surface
    # A class this run will create is as available to the type mapper as one already in the tree —
    # but only if it really will be written. A whole-class drop (unextendable superclass) has to
    # propagate: in the 2026-08-20 tree NSPanel is dropped because NSWindow is final there, and
    # without this fixpoint NSSavePanel still emitted `extends NSPanel` against a file that was
    # never written (73 cascading "cannot find symbol: peer" errors). Iterating to a stable set is
    # bounded by the number of requested classes.
    dropped = {}
    supers = {}
    while True:
        effective = dict(wrappers)
        effective.update({c: PendingCaps(c) for c in surfaces
                          if c not in wrappers and c not in dropped})
        changed = False
        for cls, surface in surfaces.items():
            if cls in dropped:
                continue
            superclass = surface.superclass if surface.superclass in effective else "NSObject"
            supers[cls] = superclass
            if surface.superclass is None and cls != "NSObject":
                # NSProxy is a root class in the SDK (its `<NSObject>` is a protocol list, not a
                # superclass). Emitting `extends NSObject` compiled but described the wrong
                # hierarchy, and the generated template needs the hand-written base for `peer`.
                dropped[cls] = ("the SDK declares no superclass; a root class needs the "
                                "hand-written NSObject base")
                changed = True
                continue
            if superclass == cls:
                # The hierarchy root is hand-written: a generated `class NSObject extends NSObject`
                # is both a compile error and missing the `peer` field every subclass uses. Drop it
                # so the shipped root stays in place for its dependents.
                dropped[cls] = "the hierarchy root is hand-written (it would extend itself)"
                changed = True
                continue
            if not toolkit.can_extend(superclass, effective):
                dropped[cls] = ("target wrapper %s cannot be extended (final or private constructor)"
                                % superclass)
                changed = True
        if not changed:
            break
    for cls in surfaces:
        if cls in dropped:
            lines.append("SKIP %s: %s" % (cls, dropped[cls]))
    for cls, surface in surfaces.items():
        if cls in dropped:
            continue
        superclass = supers[cls]
        plans = build_plan(surface, rt, vocab, effective, cls,
                           include_deprecated=not args.skip_deprecated, toolkit=toolkit)
        used = [p for p in plans if not p.skip]
        skipped = [p for p in plans if p.skip]
        lines.extend(resolve_inherited_names(plans, effective, superclass))
        # Guards the evidence asks for. A missing helper in the target tree, a parameter the
        # header named differently or a case that needs a class-local guard all show up as a
        # report line rather than a silently dropped guard.
        for q in plans:
            if q.skip:
                continue
            for case in evidence.get((cls, q.decl.selector), []):
                wanted = case.get("guards") or []
                if case.get("needs_local_guard"):
                    lines.append("    GUARD-LOCAL %s%s  [%s]" % (
                        "+" if q.is_class else "", q.decl.selector,
                        str(case["needs_local_guard"])[:70]))
                    continue
                shipped = shipped_verdicts.get(case.get("probe_id"))
                if not wanted and case.get("control") and shipped in (
                        "java-exception", "objc-abort", "sigtrap", "sigill"):
                    # Measured: the generated wrapper tolerates an argument the shipped wrapper
                    # rejects. Matching it is conformance, not extra strictness.
                    wanted = guard_template(case)
                    if wanted:
                        lines.append("    GUARD-MATCH %s%s  [the shipped wrapper rejects this "
                                     "argument]" % ("+" if q.is_class else "", q.decl.selector))
                if not wanted:
                    continue
                if any("Bounds.index" in g for g in wanted) and case.get("bound") \
                        and not bound_is_usable(case["bound"], plans, getattr(args, "repo", ".")):
                    lines.append("    GUARD-UNUSABLE-BOUND %s%s  [%s does not resolve on the "
                                 "generated class]" % ("+" if q.is_class else "",
                                                       q.decl.selector, case["bound"]))
                    continue
                if shipped == "tolerated":
                    # Measured: the shipped wrapper accepts this argument, so a guard here would
                    # make the generated wrapper stricter than the one it replaces.
                    lines.append("    GUARD-SKIPPED %s%s  [the shipped wrapper tolerates this "
                                 "argument]" % ("+" if q.is_class else "", q.decl.selector))
                    continue
                if q.is_class:
                    lines.append("    GUARD-SKIPPED %s+  [evidence case is an instance call]" %
                                 q.decl.selector)
                    continue
                names = [nm for _k, _jt, nm in q.params]
                target = case.get("param") if case.get("param") in names else None
                if target is None and isinstance(case.get("param_index"), int) \
                        and case["param_index"] < len(names):
                    target = names[case["param_index"]]
                if target is None:
                    lines.append("    GUARD-MISS %s  [no parameter named %s]" % (
                        q.decl.selector, case.get("param")))
                    continue
                need = [g.split("(")[0] for g in wanted]
                missing = [n for n in need if n in PRIMITIVES and not toolkit.has(n)]
                if missing:
                    lines.append("    GUARD-UNAVAILABLE %s  [target tree lacks %s]" % (
                        q.decl.selector, ", ".join(missing)))
                    continue
                # A selector can carry a guard per index parameter (cellAtColumnIndex:rowIndex:
                # needs both), so these accumulate: assigning meant the second replaced the first.
                q.guard_setup.extend(case.get("setup") or [])
                q.guards.extend(g.replace("{p}", target) for g in wanted)
                lines.append("    GUARD %s%s  [measured %s]" % (
                    "+" if q.is_class else "", q.decl.selector, case.get("unguarded")))
        # A member typed by a class this same run creates is not reproducible by a later run that
        # generates only this class (the other file may be missing): say so rather than let the
        # output drift silently between a batch and an incremental regeneration.
        pending_types = sorted(
            {q.ret_java for q in plans if not q.skip and q.ret_java in effective
             and q.ret_java not in wrappers}
            | {jt for q in plans if not q.skip for k, jt, _n in q.params
               if k.startswith("typed:") and jt in effective and jt not in wrappers})
        if pending_types:
            lines.append("    NOTE typed by classes this run creates: %s" % ", ".join(pending_types))
        target = os.path.join(getattr(args, "repo", "."), "src", "nsui", cls + ".java")
        if os.path.exists(target):
            before = set(re.findall(r"public\s+(?:static\s+)?[\w.<>\[\]]+\s+(\w+)\s*\(",
                                    open(target, encoding="utf-8", errors="replace").read()))
            after = {q.java_name for q in plans if not q.skip}
            lost = sorted(before - after)
            if lost:
                lines.append("    NOTE replaces an existing wrapper and drops %d public member(s): %s"
                             % (len(lost), ", ".join(lost[:6]) + ("…" if len(lost) > 6 else "")))
        rel_header = os.path.relpath(surface.file, sdk)
        text = render_class(cls, superclass, rel_header, plans, surface, surface.framework,
                            protected_init=cls in protected_init
                            or parent_init_visible(effective, superclass))
        rel = os.path.join("src", "nsui", cls + ".java")
        files.append((rel, text))
        lines.append("class %s (%s, %s): %d generated, %d skipped, extends %s"
                     % (cls, surface.framework, rel_header, len(used), len(skipped), superclass))
        # Statements no parser branch claimed. Extern constants and enum bodies are expected; a
        # method or property shape here means a declaration was dropped, which is how
        # NSDatePicker.datePickerStyle went missing while the run still said "0 skipped".
        lost = [u for iface, _fw in surface.parts for u in getattr(iface, "unparsed", [])
                if "@property" in u or re.search(r"[+-]\s*\(", u)]
        if lost:
            lines.append("    UNPARSED %d declaration-shaped statement(s), e.g. %s"
                         % (len(lost), lost[0][:90]))
        lines.append("    surface: %d header bodies merged (%s)"
                     % (len(surface.parts),
                        ", ".join(sorted(set(fw for _iface, fw in surface.parts)))))
        for p in used:
            if getattr(p, "renamed_from", None):
                lines.append("    RENAMED %s -> %s   [both sides of the selector are declared]"
                             % (p.renamed_from, p.java_name))
        for p in skipped:
            lines.append("    SKIP %s%s  [%s]" % ("" if not p.is_class else "+",
                                                  p.decl.selector, p.reason))
            if p.reason.startswith("new Sig shape "):
                vocab_needed.append((p.shape[0], tuple(p.shape[1]), cls, p.decl.selector))
            if p.reason.startswith("new Sig shape"):
                new_shape_counter[p.reason] = new_shape_counter.get(p.reason, 0) + 1
    lines.append("")
    if new_shape_counter:
        lines.append("new Sig shapes required (%d distinct):" % len(new_shape_counter))
        for k in sorted(new_shape_counter):
            lines.append("    %s" % k)
    else:
        lines.append("new Sig shapes required: none")
    return files, lines, vocab_needed


def main(argv=None):
    ap = argparse.ArgumentParser(description="nsui code generator (stdlib only)")
    ap.add_argument("--repo", default=".", help="target repo root (never written without --apply)")
    ap.add_argument("--class", dest="classes", action="append", default=[],
                    help="ObjC class to generate (repeatable)")
    ap.add_argument("--framework", dest="frameworks", action="append", default=[],
                    help="framework to search for headers (repeatable)")
    ap.add_argument("--apply", action="store_true",
                    help="write changed files into --repo (default: patch only)")
    ap.add_argument("--shipped-baseline", metavar="PATH",
                    help="measured shipped-wrapper verdicts (default codegen/shipped-baseline.json "
                         "next to gen.py); a case with no verdict is guarded")
    ap.add_argument("--guard-evidence", metavar="PATH",
                    help="measured bad-argument evidence (default codegen/guard-evidence.json)")
    ap.add_argument("--vocab-patch", metavar="PATH",
                    help="write a reviewable diff adding the Sig shapes this run needed but "
                         "the target vocabulary lacks")
    ap.add_argument("--check", action="store_true",
                    help="print the diff and exit 1 on drift; write nothing")
    ap.add_argument("--skip-deprecated", action="store_true")
    ap.add_argument("--patch-out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "proposed.patch"))
    ap.add_argument("--summary-out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "summary.txt"))
    ap.add_argument("--scratch", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".patchscratch"))
    ap.add_argument("--survey", nargs="*", default=None,
                    help="survey the named frameworks (default AppKit QuartzCore)")
    args = ap.parse_args(argv)
    if not args.frameworks:
        args.frameworks = ["AppKit", "Foundation", "QuartzCore"]
    if args.survey is not None:
        return survey(args.survey or ["AppKit", "QuartzCore"], args)

    sdk = find_sdk()
    repo = os.path.abspath(args.repo)
    vocab = load_vocabulary(os.path.join(repo, "src", "nsui", "objc", "Sig.java"))
    wrappers = load_wrappers(os.path.join(repo, "src", "nsui"))
    fws = list(dict.fromkeys(args.frameworks + ["AppKit", "Foundation", "QuartzCore"]))
    rt = objcabi.ObjCRuntime(fws)
    files, summary_lines, vocab_needed = gen_classes(args, sdk, vocab, wrappers, rt)
    if vocab_needed:
        distinct = len({(r, tuple(a)) for r, a, _c, _s in vocab_needed})
        print("NOTE %d method(s) need %d Sig shape(s) the target vocabulary lacks"
              % (len(vocab_needed), distinct))
        if args.vocab_patch:
            diff, rel = vocab_patch(repo, vocab_needed)
            if diff:
                with open(args.vocab_patch, "w", encoding="utf-8") as fh:
                    fh.write(diff)
                print("vocabulary patch: %s (%d shapes in %s)"
                      % (args.vocab_patch, distinct, rel))
            else:
                print("vocabulary patch: could not read %s" % rel)
    if not files:
        # Every requested class was skipped (no @interface, or unknown): reporting success here
        # would hide that nothing was generated at all.
        sys.stdout.write("\n".join(summary_lines) + "\n")
        print("nothing rendered for the requested classes (see the SKIP lines above)")
        return 1
    patch, pending = make_patch(repo, files, args.scratch)
    summary = "\n".join(summary_lines) + "\n"
    if args.check:
        sys.stdout.write(summary)
        sys.stdout.write(patch if patch else "(no drift: generated output already matches the tree)\n")
        return 1 if patch else 0
    with open(args.patch_out, "w", encoding="utf-8") as fh:
        fh.write(patch)
    with open(args.summary_out, "w", encoding="utf-8") as fh:
        fh.write(summary)
    print(summary)
    for rel, _t in files:
        status = "modified/new" if any(r == rel for r, _b, _n in pending) else "unchanged"
        print("%-8s %s" % (status, rel))
    if pending:
        print("patch: %s (%d bytes)" % (args.patch_out, len(patch)))
    else:
        print("no diff")
    if args.apply:
        written, _unchanged = apply_plan(repo, pending)
        print("applied to %s: %s" % (repo, ", ".join(written) if written else "(nothing to write)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())

