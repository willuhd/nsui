def load_vocabulary(sig_path):
    text = open(sig_path, encoding="utf-8", errors="replace").read()
    pat = re.compile(r"of\(\s*Ret\.(\w+)\s*((?:,\s*Arg\.\w+\s*)*)\)")
    vocab = set()
    for m in pat.finditer(text):
        ret = m.group(1)
        args = tuple(re.findall(r"Arg\.(\w+)", m.group(2)))
        vocab.add((ret, args))
    return vocab


class Caps:
    """What the existing hand-written wrapper for a class can do."""

    __slots__ = ("name", "wrap", "to_segment", "from_segment", "slot", "path")

    def __init__(self, name, path):
        self.name = name
        self.path = path
        text = open(path, encoding="utf-8", errors="replace").read()
        self.wrap = bool(re.search(r"static\s+%s\s+wrap\s*\(\s*MemorySegment" % re.escape(name), text))
        self.to_segment = "toSegment(" in text
        self.from_segment = "fromSegment(" in text
        self.slot = "SegmentAllocator slot(" in text


class PendingCaps:
    """A wrapper this run is about to create.

    Registering planned classes before planning is what makes a multi-class run independent of
    order: without it, a class returning a type that is also being generated in the same run was
    typed as a raw MemorySegment or as the wrapper depending on which class was processed first,
    so the same invocation produced different files.
    """

    __slots__ = ("name", "wrap", "to_segment", "from_segment", "slot", "path")

    def __init__(self, name):
        self.name = name
        self.wrap = True             # the template always emits wrap(MemorySegment)
        self.to_segment = False      # and never toSegment/fromSegment/slot, which are hand-written
        self.from_segment = False
        self.slot = False
        self.path = ""


class _EmptyCaps:
    name = ""
    path = ""
    wrap = to_segment = from_segment = slot = False


_EMPTY_CAPS = _EmptyCaps()


def load_wrappers(src_dir):
    out = {}
    if not os.path.isdir(src_dir):
        return out
    for fn in sorted(os.listdir(src_dir)):
        if not fn.endswith(".java"):
            continue
        name = fn[:-5]
        out[name] = Caps(name, os.path.join(src_dir, fn))
    return out


def parent_init_visible(wrappers, superclass):
    """True when the target's wrapper for `superclass` declares ensureInit non-private.

    Java forbids hiding a static method with reduced visibility, so a generated subclass of a
    parent with `protected static void ensureInit()` cannot declare it private — the current
    tree's NSTableView is exactly that, and NSOutlineView failed to compile because of it.
    """
    cap = wrappers.get(superclass)
    if cap is None:
        return False
    try:
        text = open(cap.path, encoding="utf-8", errors="replace").read()
    except OSError:
        return False
    for name in ("ensureInit", "ensureInitLocked"):
        if re.search(r"private\s+static\s+(?:synchronized\s+)?void\s+%s\s*\(" % name, text):
            continue
        if re.search(r"\bstatic\s+(?:synchronized\s+)?void\s+%s\s*\(" % name, text):
            return True
    return False


def inherited_members(wrappers, superclass):
    """{member name: {is_static, ...}} for the target tree's wrapper chain above `superclass`.

    Java forbids an instance method overriding a static one (and a static hiding an instance), but
    Objective-C is happy to declare both on a subclass — NSControl has `+cellClass` while NSMatrix
    has `-cellClass`. The generator has to know what it is inheriting to avoid emitting a class
    that cannot compile.
    """
    out = {}
    seen = set()
    cur = superclass
    while cur and cur in wrappers and cur not in seen:
        seen.add(cur)
        cap = wrappers[cur]
        try:
            text = open(cap.path, encoding="utf-8", errors="replace").read()
        except OSError:
            break
        for m in re.finditer(r"^\s*public\s+(static\s+)?([\w.<>\[\]]+)\s+(\w+)\s*\(([^)]*)\)",
                             text, re.M):
            params = m.group(4).strip()
            arity = 0 if not params else params.count(",") + 1
            out.setdefault(m.group(3), []).append((arity, bool(m.group(1)), m.group(2)))
        mm = re.search(r"\bclass\s+\w+\s+extends\s+(\w+)", text)
        cur = mm.group(1) if mm else None
    return out


def subclasses_using_init(wrappers):
    """Class names whose `ensureInit()` some other wrapper in the target tree calls.

    The shipped corpus sets the visibility per class: NSGestureRecognizer.ensureInit() is
    `protected static` because its five subclasses call it, while NSControl and NSText keep it
    private. Emitting `private` for a class whose siblings call it breaks their compile, so the
    emission follows the tree rather than a fixed template.
    """
    needed = set()
    pat = re.compile(r"\b(\w+)\.ensureInit\(\)")
    for cap in wrappers.values():
        try:
            text = open(cap.path, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        needed.update(pat.findall(text))
    return needed


# Primitives the renderer may emit, and the file+pattern that must exist in the TARGET tree for it.
# A tree that lacks one cannot compile a method that needs it, so the plan is skipped with a
# nameable reason instead of emitting code that cannot build. Extend the table rather than adding
# per-class exceptions: the point is that the generator only emits what its target provides.
PRIMITIVES = {
    "ObjC.structSlot": ("src/nsui/objc/ObjC.java", r"\bstructSlot\s*\("),
    "Bounds.nonNull": ("src/nsui/Bounds.java", r"\bnonNull\s*\("),
    "Bounds.index": ("src/nsui/Bounds.java", r"\bindex\s*\("),
    "Bounds.notNaN": ("src/nsui/Bounds.java", r"\bnotNaN\s*\("),
}


class Toolkit:
    """What the tree being generated into provides."""

    def __init__(self, repo):
        self.repo = repo
        self._cache = {}

    def has(self, primitive):
        if primitive not in self._cache:
            rel, pattern = PRIMITIVES[primitive]
            try:
                text = open(os.path.join(self.repo, rel), encoding="utf-8", errors="replace").read()
            except OSError:
                text = ""
            self._cache[primitive] = re.search(pattern, text) is not None
        return self._cache[primitive]

    def missing(self):
        return sorted(p for p in PRIMITIVES if not self.has(p))

    def can_extend(self, superclass, wrappers):
        """False when the target's wrapper for `superclass` is final or has a private constructor.

        A generated subclass of either cannot compile, and both are real in the history (the
        2026-08-20 tree has `final class NSTableView` with a private (MemorySegment) constructor).
        """
        cap = wrappers.get(superclass)
        if cap is None:
            return True
        try:
            text = open(cap.path, encoding="utf-8", errors="replace").read()
        except OSError:
            return True
        if re.search(r"\bfinal\s+class\s+%s\b" % re.escape(superclass), text):
            return False
        return not re.search(r"private\s+%s\s*\(\s*MemorySegment" % re.escape(superclass), text)


# ------------------------------------------------------------ java name/type

def base_type(raw):
    """'nullable NSArray<NSString *> *' -> 'NSArray'."""
    t = raw or ""
    t = re.sub(r"\b(nullable|nonnull|__kindof|IBOutlet|IBAction|inout|out|oneway|bycopy|byref"
               r"|const|volatile)\b|_Nullable|_Nonnull", " ", t)
    t = re.sub(r"<[^<>]*>", " ", t)
    t = t.replace("*", " ").replace("^", " ")
    t = t.strip()
    m = re.match(r"([A-Za-z_]\w*)", t)
    return m.group(1) if m else ""


def is_string(raw):
    return base_type(raw) == "NSString"


# Contextual and reserved words that cannot be a Java identifier. `+[NSNull null]` produced
# `public static NSNull null()` and three syntax errors in an otherwise clean 389-class run.
JAVA_RESERVED = set(JAVA_KEYWORDS) | {"var", "record", "yield", "sealed", "permits", "_",
                                      "true", "false", "null"}

# java.lang.Object's final methods cannot be overridden, so a selector that lands on one
# (`-[NSCondition wait]`) has to take a different name.
OBJECT_FINAL_SIGS = {("wait", 0), ("wait", 1), ("wait", 2), ("notify", 0), ("notifyAll", 0),
                     ("getClass", 0)}


def safe_java_name(name):
    """A Java identifier that is not a reserved word; a clash takes a trailing underscore."""
    return name + "_" if name in JAVA_RESERVED else name


def selector_field(selector):
    parts = [p for p in selector.split(":") if p]
    if not parts:
        return "sel"
    return safe_java_name(re.sub(r"\W", "_", "_".join([parts[0]] + parts[1:])))


def java_method_name(selector):
    parts = [p for p in selector.split(":") if p]
    if not parts:
        return "sel"
    name = parts[0]
    for p in parts[1:]:
        name += p[0].upper() + p[1:]
    return safe_java_name(re.sub(r"\W", "_", name))


def param_name(raw, i):
    n = raw or ""
    if n in JAVA_KEYWORDS or not n:
        n = "arg%d" % i
    return n


# ---------------------------------------------------------------- method plan

class Plan:
    __slots__ = ("decl", "shape", "enc", "kind", "is_class", "skip", "reason",
                 "java_name", "field", "handle", "params", "ret_kind", "ret_java", "renamed_from",
                 "guards", "guard_setup")

    def __init__(self, decl):
        self.decl = decl
        self.shape = None
        self.enc = None
        self.kind = None
        self.is_class = decl.is_class
        self.skip = None
        self.reason = None
        self.java_name = None
        self.field = None
        self.handle = None
        self.params = []
        self.ret_kind = None
        self.renamed_from = None
        self.guards = []
        self.guard_setup = []
        self.ret_java = None


def classify_param_java(abi_class, raw, name, wrappers, cls_name, token=None):
    """Returns ('kind', java_type) where kind drives the argument expression."""
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name:
            return "typed:" + cls_name, cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed:" + b, b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        # uint32_t / unsigned int: a 4-byte descriptor with a 32-bit unsigned value. The
        # house form carries it in a Java long and narrows at the call (see
        # MTLStencilDescriptor.setReadMask:), so a mask with bit 31 set stays positive.
        return "uint32", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def classify_ret_java(abi_class, raw, wrappers, cls_name, token=None):
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name or b == "instancetype":
            return "typed", cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed", b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        return "uint32", "long"
    if abi_class == "SHORT" and token == "S":
        # unsigned short: read 16 bits and zero-extend into the long surface, the house form in
        # NSLayoutManager.CGGlyphAtIndex (`return glyph & 0xFFFFL;`). Without the mask a glyph
        # with bit 15 set came back negative.
        return "uint16", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def build_plan(surface, rt, vocab, wrappers, cls_name, include_deprecated=True, toolkit=None):
    plans = []
    seen_names = {}
    for decl in surface.decls:
        p = Plan(decl)
        sel = decl.selector
        p.field = selector_field(sel)
        p.java_name = java_method_name(sel)
        if (p.java_name, len(decl.params)) in OBJECT_FINAL_SIGS:
            p.renamed_from = p.java_name
            p.java_name += "_"
        if decl.unavailable:
            p.skip, p.reason = True, "NS_UNAVAILABLE"
        elif sel in BLACKLIST or is_construction_selector(sel):
            p.skip, p.reason = True, "runtime-owned/blacklisted"
        elif any(par.is_block for par in decl.params):
            p.skip, p.reason = True, "block parameter (needs an upcall stub)"
        elif any(par.is_out for par in decl.params):
            p.skip, p.reason = True, "out-parameter / pointer-to-scalar"
        elif "..." in decl.raw:
            p.skip, p.reason = True, "variadic"
        elif is_init_family(sel, decl.ret_raw):
            p.skip, p.reason = True, "initializer (construction is hand-written)"
        elif not include_deprecated and decl.deprecated:
            p.skip, p.reason = True, "deprecated"
        if p.skip:
            plans.append(p)
            continue
        enc, kind = rt.encoding(cls_name, sel, decl.is_class)
        if enc is None:
            p.skip, p.reason = True, "runtime: " + kind
            plans.append(p)
            continue
        p.enc, p.kind = enc, kind
        shape = objcabi.shape_of(enc)
        if shape is None:
            p.skip, p.reason = True, "unparseable encoding"
            plans.append(p)
            continue
        p.shape = shape
        toks = objcabi.parse_types(enc)
        ret, args = shape
        if p.skip:
            plans.append(p)
            continue
        # The encoding, not the type name, says whether a parameter is a pointer: an object is `@`,
        # an out slot is `^` (`NSError **`, `NSRange *`, `CGFloat *`, typedef'd NSRangePointer).
        # Name-based guesses both missed `nullable CGFloat *` and over-skipped unwrapped object
        # classes (`NSURL *`), which is why this is derived from the ABI.
        raw_toks = objcabi.parse_types_raw(enc)
        if any(token_is_pointer(raw_toks[3 + i] if 3 + i < len(raw_toks) else None)
               for i in range(len(decl.params))):
            p.skip, p.reason = True, "out-parameter / pointer-to-scalar"
            plans.append(p)
            continue
        if (ret, args) not in vocab:
            p.skip = True
            p.reason = "new Sig shape %s(%s)" % (ret, ", ".join(args))
            plans.append(p)
            continue
        # kind consistency (instance vs class) between header and runtime
        if (decl.is_class and kind != "class") or (not decl.is_class and kind != "inst"):
            p.skip = True
            p.reason = "header says %s but runtime has only %s" % (
                "class" if decl.is_class else "instance", kind)
            plans.append(p)
            continue
        # struct capability checks
        bad = None
        for a, par in zip(args, decl.params):
            if a in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[a], _EMPTY_CAPS).to_segment:
                bad = "no toSegment() for " + STRUCT_JAVA[a]
        if ret in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[ret], _EMPTY_CAPS).from_segment:
            bad = "no fromSegment() for " + STRUCT_JAVA[ret]
        if ret == "TRANSFORM3D" and not (wrappers.get("CATransform3D") and wrappers["CATransform3D"].slot):
            bad = "no slot() for CATransform3D"
        if ret in STRUCT_JAVA and ret != "TRANSFORM3D" and toolkit is not None \
                and not toolkit.has("ObjC.structSlot"):
            bad = "target tree has no ObjC.structSlot()"
        if bad:
            p.skip, p.reason = True, bad
            plans.append(p)
            continue
        # A selector declared on both sides (NSDate has +timeIntervalSinceReferenceDate and an
        # instance property of the same name) maps to one Java name. Java can hold both, but only
        # under distinct names, so the second side is renamed rather than dropped; a true duplicate
        # — same side, same arity — keeps the first declaration, which is deterministic because
        # decls are ordered.
        prev = seen_names.get(p.java_name)
        if prev is not None:
            prev_class, prev_arity = prev
            if prev_class == p.is_class or prev_arity != len(p.params):
                p.skip, p.reason = True, "duplicate Java name (first declared wins)"
                plans.append(p)
                continue
            base_name = p.java_name
            p.java_name += "Class" if p.is_class else "Instance"
            while p.java_name in seen_names:
                p.java_name += "_"
            p.renamed_from = base_name
        seen_names[p.java_name] = (p.is_class, len(p.params))
        p.ret_kind, p.ret_java = classify_ret_java(
            ret, decl.ret_raw, wrappers, cls_name, toks[0] if toks else None)
        for i, (a, par) in enumerate(zip(args, decl.params)):
            tok = toks[3 + i] if 3 + i < len(toks) else None
            k, jt = classify_param_java(a, par.type_raw, par.name, wrappers, cls_name, tok)
            p.params.append((k, jt, param_name(par.name, i)))
        p.handle = "h_" + ret + "".join("_" + a for a in args)
        plans.append(p)
    return plans


def apply_skip_gates(plans, include_deprecated=True):
    """Blacklist / feature gates applied before touching the runtime."""
    return plans


