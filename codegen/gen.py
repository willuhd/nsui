def classify_param_java(abi_class, raw, name, wrappers, cls_name, token=None):
    """Returns ('kind', java_type) where kind drives the argument expression."""
    if token and (token.startswith("^") or token == "*"):
        # An address: an out-parameter slot (`NSError **`), a buffer (`const float *`) or a C
        # string. The caller supplies the memory; the call passes its address, which is exactly
        # what the ABI's 64-bit slot carries. Without this the whole method was skipped.
        return "ptr", "MemorySegment"
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name:
            return "typed:" + cls_name, cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed:" + b, b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        # uint32_t / unsigned int: a 4-byte descriptor with a 32-bit unsigned value. The
        # house form carries it in a Java long and narrows at the call (see
        # MTLStencilDescriptor.setReadMask:), so a mask with bit 31 set stays positive.
        return "uint32", "long"
    # R3: NSUInteger kind. The ABI collapses NSInteger (q/l) and NSUInteger (Q/L) to one INT
    # shape, so the vocabulary is unchanged; the kind keeps the signedness the encoding had.
    # A negative Java long passed as NSUInteger wraps to a huge unsigned value natively
    # (measured aborts on scissor components, buffer lengths, array capacities), so a future
    # nonNegative guard needs to tell the two apart. The call emission is identical to long.
    if abi_class == "INT" and token in ("Q", "L"):
        return "ulong", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def classify_ret_java(abi_class, raw, wrappers, cls_name, token=None):
    if token and (token.startswith("^") or token == "*"):
        return "ptr", "MemorySegment"
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name or b == "instancetype":
            return "typed", cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed", b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        return "uint32", "long"
    # R3: NSUInteger return kind, mirroring the parameter side. The shape stays INT so the
    # vocabulary is unchanged; the kind records that the value is unsigned (a negative Java
    # long would wrap). The exact-width read below still casts to long, as for INT.
    if abi_class == "INT" and token in ("Q", "L"):
        return "ulong", "long"
    if abi_class == "BYTE" and token == "C":
        # unsigned char: the handle returns a signed byte, so -1 for 255 unless it is masked into
        # the long surface, exactly as uint16 and uint32 are. The shipped NSNumber.unsignedCharValue
        # does this; the generated one returned -1 for 65535's low byte.
        return "uint8", "long"
    if abi_class == "SHORT" and token == "S":
        # unsigned short: read 16 bits and zero-extend into the long surface, the house form in
        # NSLayoutManager.CGGlyphAtIndex (`return glyph & 0xFFFFL;`). Without the mask a glyph
        # with bit 15 set came back negative.
        return "uint16", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def build_plan(surface, rt, vocab, wrappers, cls_name, include_deprecated=True, toolkit=None):
    plans = []
    seen_names = {}
    for decl in surface.decls:
        p = Plan(decl)
        sel = decl.selector
        p.field = selector_field(sel)
        p.java_name = java_method_name(sel)
        if (p.java_name, len(decl.params)) in OBJECT_FINAL_SIGS:
            p.renamed_from = p.java_name
            p.java_name += "_"
        if decl.unavailable:
            p.skip, p.reason = True, "NS_UNAVAILABLE"
        elif sel in BLACKLIST or is_construction_selector(sel):
            p.skip, p.reason = True, "runtime-owned/blacklisted"
        elif "..." in decl.raw:
            p.skip, p.reason = True, "variadic"
        elif is_init_family(sel, decl.ret_raw) and not decl.is_class:
            # The shipped corpus hand-writes a `create` factory per class. A class the toolkit never
            # wrapped has none, so without this the generated wrapper could not be constructed at
            # all: it has wrap(peer) and nothing that produces a peer.
            p.is_constructor = True
        elif is_init_family(sel, decl.ret_raw):
            p.skip, p.reason = True, "class-side initializer"
        elif not include_deprecated and decl.deprecated:
            p.skip, p.reason = True, "deprecated"
        if p.is_constructor:
            # `initWithFrame:` -> `createWithFrame`; `init` -> `create`. Derived from the selector
            # rather than a fixed name, so several initializers overload or coexist clearly. This
            # has to happen after the skip decision, which is what marks a plan as a constructor.
            rest = p.java_name[len("init"):] if p.java_name.startswith("init") else p.java_name
            p.java_name = "create" + rest
        if p.skip:
            plans.append(p)
            continue
        enc, kind = rt.encoding(cls_name, sel, decl.is_class)
        if enc is None:
            p.skip, p.reason = True, "runtime: " + kind
            plans.append(p)
            continue
        p.enc, p.kind = enc, kind
        shape = objcabi.shape_of(enc)
        if shape is None:
            p.skip, p.reason = True, "unparseable encoding"
            plans.append(p)
            continue
        p.shape = shape
        toks = objcabi.parse_types(enc)
        ret, args = shape
        if p.skip:
            plans.append(p)
            continue
        # The encoding, not the type name, says whether a parameter is a pointer: an object is `@`,
        # an out slot is `^` (`NSError **`, `NSRange *`, `CGFloat *`, typedef'd NSRangePointer).
        # Name-based guesses both missed `nullable CGFloat *` and over-skipped unwrapped object
        # classes (`NSURL *`), which is why this is derived from the ABI.
        raw_toks = objcabi.parse_types_raw(enc)
        if (ret, args) not in vocab:
            p.skip = True
            # Name the struct the encoding mentions when there is one: "new Sig shape VOID(OTHER)"
            # hides that the real obstacle is a hand-written struct wrapper the toolkit lacks
            # (CAMetalDisplayLink's preferredFrameRateRange is CAFrameRateRange), and that is the
            # one thing a reader can act on.
            # Name a struct only when its ABI kind is unrepresentable, which is the case a reader
            # can act on by adding a wrapper class. A known kind missing this particular combination
            # (`ID(RECT, ID)`, where RECT is fine and NSRect exists) is a vocabulary gap, and
            # blaming a struct that already exists sent the reader after the wrong thing.
            unknown_kind = ret == "OTHER" or "OTHER" in args
            structs = []
            if unknown_kind:
                # parse_types_raw is [return, self, _cmd, arg...]: the return is index 0, the
                # parameters start at 3.
                for tok in raw_toks[3:3 + len(decl.params)] + (raw_toks[:1] or [None]):
                    m = re.match(r"\{([A-Za-z_]\w*)=", tok or "")
                    if m and m.group(1) not in structs:
                        structs.append(m.group(1))
            p.reason = ("the toolkit has no %s struct (add it to src/nsui)" % ", ".join(structs)
                        if structs else "new Sig shape %s(%s)" % (ret, ", ".join(args)))
            plans.append(p)
            continue
        # kind consistency (instance vs class) between header and runtime
        if (decl.is_class and kind != "class") or (not decl.is_class and kind != "inst"):
            p.skip = True
            p.reason = "header says %s but runtime has only %s" % (
                "class" if decl.is_class else "instance", kind)
            plans.append(p)
            continue
        # struct capability checks
        bad = None
        for a, par in zip(args, decl.params):
            if a in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[a], _EMPTY_CAPS).to_segment:
                bad = "no toSegment() for " + STRUCT_JAVA[a]
        if ret in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[ret], _EMPTY_CAPS).from_segment:
            bad = "no fromSegment() for " + STRUCT_JAVA[ret]
        if ret == "TRANSFORM3D" and not (wrappers.get("CATransform3D") and wrappers["CATransform3D"].slot):
            bad = "no slot() for CATransform3D"
        if ret in STRUCT_JAVA and ret != "TRANSFORM3D" and toolkit is not None \
                and not toolkit.has("ObjC.structSlot"):
            bad = "target tree has no ObjC.structSlot()"
        if bad:
            p.skip, p.reason = True, bad
            plans.append(p)
            continue
        # A selector declared on both sides (NSDate has +timeIntervalSinceReferenceDate and an
        # instance property of the same name) maps to one Java name. Java can hold both, but only
        # under distinct names, so the second side is renamed rather than dropped; a true duplicate
        # — same side, same arity — keeps the first declaration, which is deterministic because
        # decls are ordered.
        prev = seen_names.get(p.java_name)
        if prev is not None:
            prev_class, prev_arity = prev
            if prev_class == p.is_class or prev_arity != len(p.params):
                p.skip, p.reason = True, "duplicate Java name (first declared wins)"
                plans.append(p)
                continue
            base_name = p.java_name
            p.java_name += "Class" if p.is_class else "Instance"
            while p.java_name in seen_names:
                p.java_name += "_"
            p.renamed_from = base_name
        seen_names[p.java_name] = (p.is_class, len(p.params))
        # The raw token stream, matching shape_of: the normalized stream has already collapsed a
        # pointer (`^@`) into ID, so a parameter the shape calls INT arrived here as a scalar and
        # was typed `long` — an address in a long where the design says MemorySegment.
        p.ret_kind, p.ret_java = classify_ret_java(
            ret, decl.ret_raw, wrappers, cls_name, raw_toks[0] if raw_toks else None)
        for i, (a, par) in enumerate(zip(args, decl.params)):
            tok = raw_toks[3 + i] if 3 + i < len(raw_toks) else None
            k, jt = classify_param_java(a, par.type_raw, par.name, wrappers, cls_name, tok)
            p.params.append((k, jt, param_name(par.name, i)))
        p.handle = "h_" + ret + "".join("_" + a for a in args)
        plans.append(p)
    return plans


def apply_skip_gates(plans, include_deprecated=True):
    """Blacklist / feature gates applied before touching the runtime."""
    return plans


