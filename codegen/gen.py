VERSION = "0.1.2"   # 0.1 stays; .xx is the minor revision (user-controlled)
MARKER = "/// @generated by CodeGen @version " + VERSION

# Selections the generator refuses to emit even when ABI-identical: they are
# runtime-owned, or the base wrapper deliberately gives them different semantics.
BLACKLIST = {
    "init", "new", "alloc", "dealloc", "retain", "release", "autorelease",
    "retainCount", "hash", "class", "description", "debugDescription", "copy",
    "mutableCopy", "self", "superclass", "zone", "respondsToSelector:",
    "isKindOfClass:", "isMemberOfClass:", "forwardInvocation:",
    "methodSignatureForSelector:", "doesNotRecognizeSelector:",
    "initWithCoder:", "encodeWithCoder:", "awakeAfterUsingCoder:",
    "replacementObjectForCoder:", "classForCoder", "finalize", "load",
    "initialize", "poseAsClass:", "conformsToProtocol:", "performSelector:",
    "performSelector:withObject:", "performSelector:withObject:withObject:",
}

JAVA_KEYWORDS = {
    "abstract", "assert", "boolean", "break", "byte", "case", "catch", "char",
    "class", "const", "continue", "default", "do", "double", "else", "enum",
    "extends", "final", "finally", "float", "for", "goto", "if", "implements",
    "import", "instanceof", "int", "interface", "long", "native", "new",
    "package", "private", "protected", "public", "return", "short", "static",
    "strictfp", "super", "switch", "synchronized", "this", "throw", "throws",
    "transient", "try", "void", "volatile", "while", "record", "var", "yield",
}

STRUCT_JAVA = {
    "RECT": "NSRect", "POINT": "NSPoint", "SIZE": "NSSize", "RANGE": "NSRange",
    "TRANSFORM3D": "CATransform3D", "EDGEINSETS": "NSEdgeInsets",
}
SCALAR_JAVA = {"INT": "long", "BOOL": "boolean", "DOUBLE": "double", "FLOAT": "float",
               "BYTE": "byte", "VOID": "void", "INT32": "int", "SHORT": "short"}
# Argument-expression kind per ABI class: the renderer switches on these strings.
SCALAR_KIND = {"INT": "long", "BOOL": "boolean", "DOUBLE": "double", "FLOAT": "float",
               "BYTE": "byte", "VOID": "void", "INT32": "int", "SHORT": "short"}
UNSUPPORTED_ARGS = {"REGION", "MTLVIEWPORT", "MTLSCISSORRECT"}


# ----------------------------------------------------------------- vocabulary

def load_vocabulary(sig_path):
    text = open(sig_path, encoding="utf-8", errors="replace").read()
    pat = re.compile(r"of\(\s*Ret\.(\w+)\s*((?:,\s*Arg\.\w+\s*)*)\)")
    vocab = set()
    for m in pat.finditer(text):
        ret = m.group(1)
        args = tuple(re.findall(r"Arg\.(\w+)", m.group(2)))
        vocab.add((ret, args))
    return vocab


class Caps:
    """What the existing hand-written wrapper for a class can do."""

    __slots__ = ("name", "wrap", "to_segment", "from_segment", "slot", "path")

    def __init__(self, name, path):
        self.name = name
        self.path = path
        text = open(path, encoding="utf-8", errors="replace").read()
        self.wrap = bool(re.search(r"static\s+%s\s+wrap\s*\(\s*MemorySegment" % re.escape(name), text))
        self.to_segment = "toSegment(" in text
        self.from_segment = "fromSegment(" in text
        self.slot = "SegmentAllocator slot(" in text


class _EmptyCaps:
    name = ""
    path = ""
    wrap = to_segment = from_segment = slot = False


_EMPTY_CAPS = _EmptyCaps()


def load_wrappers(src_dir):
    out = {}
    if not os.path.isdir(src_dir):
        return out
    for fn in sorted(os.listdir(src_dir)):
        if not fn.endswith(".java"):
            continue
        name = fn[:-5]
        out[name] = Caps(name, os.path.join(src_dir, fn))
    return out


# ------------------------------------------------------------ java name/type

def base_type(raw):
    """'nullable NSArray<NSString *> *' -> 'NSArray'."""
    t = raw or ""
    t = re.sub(r"\b(nullable|nonnull|__kindof)\b|_Nullable|_Nonnull", " ", t)
    t = re.sub(r"<[^<>]*>", " ", t)
    t = t.replace("*", " ").replace("^", " ")
    t = t.strip()
    m = re.match(r"([A-Za-z_]\w*)", t)
    return m.group(1) if m else ""


def is_string(raw):
    return base_type(raw) == "NSString"


def selector_field(selector):
    parts = [p for p in selector.split(":") if p]
    if not parts:
        return "sel"
    return re.sub(r"\W", "_", "_".join([parts[0]] + parts[1:]))


def java_method_name(selector):
    parts = [p for p in selector.split(":") if p]
    if not parts:
        return "sel"
    name = parts[0]
    for p in parts[1:]:
        name += p[0].upper() + p[1:]
    return re.sub(r"\W", "_", name)


def param_name(raw, i):
    n = raw or ""
    if n in JAVA_KEYWORDS or not n:
        n = "arg%d" % i
    return n


# ---------------------------------------------------------------- method plan

class Plan:
    __slots__ = ("decl", "shape", "enc", "kind", "is_class", "skip", "reason",
                 "java_name", "field", "handle", "params", "ret_kind", "ret_java")

    def __init__(self, decl):
        self.decl = decl
        self.shape = None
        self.enc = None
        self.kind = None
        self.is_class = decl.is_class
        self.skip = None
        self.reason = None
        self.java_name = None
        self.field = None
        self.handle = None
        self.params = []
        self.ret_kind = None
        self.ret_java = None


def classify_param_java(abi_class, raw, name, wrappers, cls_name, token=None):
    """Returns ('kind', java_type) where kind drives the argument expression."""
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name:
            return "typed:" + cls_name, cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed:" + b, b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        # uint32_t / unsigned int: a 4-byte descriptor with a 32-bit unsigned value. The
        # house form carries it in a Java long and narrows at the call (see
        # MTLStencilDescriptor.setReadMask:), so a mask with bit 31 set stays positive.
        return "uint32", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def classify_ret_java(abi_class, raw, wrappers, cls_name, token=None):
    if abi_class == "ID":
        if is_string(raw):
            return "string", "String"
        b = base_type(raw)
        if b == cls_name or b == "instancetype":
            return "typed", cls_name
        if b in wrappers and wrappers[b].wrap:
            return "typed", b
        return "id", "MemorySegment"
    if abi_class == "INT32" and token == "I":
        return "uint32", "long"
    if abi_class in SCALAR_JAVA:
        return SCALAR_KIND[abi_class], SCALAR_JAVA[abi_class]
    if abi_class in STRUCT_JAVA:
        return abi_class.lower(), STRUCT_JAVA[abi_class]
    return "unsupported", "MemorySegment"


def build_plan(iface, rt, vocab, wrappers, cls_name, include_deprecated=True):
    plans = []
    seen_names = {}
    for decl in iface.decls:
        p = Plan(decl)
        sel = decl.selector
        p.field = selector_field(sel)
        p.java_name = java_method_name(sel)
        if decl.unavailable:
            p.skip, p.reason = True, "NS_UNAVAILABLE"
        elif sel in BLACKLIST:
            p.skip, p.reason = True, "runtime-owned/blacklisted"
        elif any(par.is_block for par in decl.params):
            p.skip, p.reason = True, "block parameter (needs an upcall stub)"
        elif any(par.is_out for par in decl.params) or any(
                re.match(r"^\s*(id|NSError|NSRect|CGRect|NSPoint|CGPoint|NSSize|CGSize|"
                         r"NSRange|CGFloat|NSInteger|NSUInteger|BOOL|double|float|int|long|"
                         r"NSRectEdge)\s*\*\s*$", par.type_raw or "") for par in decl.params):
            p.skip, p.reason = True, "out-parameter / pointer-to-scalar"
        elif "..." in decl.raw:
            p.skip, p.reason = True, "variadic"
        elif sel.startswith("init"):
            p.skip, p.reason = True, "initializer (construction is hand-written)"
        elif not include_deprecated and decl.deprecated:
            p.skip, p.reason = True, "deprecated"
        if p.skip:
            plans.append(p)
            continue
        enc, kind = rt.encoding(cls_name, sel)
        if enc is None:
            p.skip, p.reason = True, "runtime: " + kind
            plans.append(p)
            continue
        p.enc, p.kind = enc, kind
        shape = objcabi.shape_of(enc)
        if shape is None:
            p.skip, p.reason = True, "unparseable encoding"
            plans.append(p)
            continue
        p.shape = shape
        toks = objcabi.parse_types(enc)
        ret, args = shape
        if p.skip:
            plans.append(p)
            continue
        if (ret, args) not in vocab:
            p.skip = True
            p.reason = "new Sig shape %s(%s)" % (ret, ", ".join(args))
            plans.append(p)
            continue
        if ret in UNSUPPORTED_ARGS:
            p.skip, p.reason = True, "no Java value type for struct ret " + ret
            plans.append(p)
            continue
        if any(a in UNSUPPORTED_ARGS for a in args):
            p.skip, p.reason = True, "no Java value type for struct arg in " + str(args)
            plans.append(p)
            continue
        # kind consistency (instance vs class) between header and runtime
        if (decl.is_class and kind != "class") or (not decl.is_class and kind != "inst"):
            p.skip = True
            p.reason = "header says %s but runtime has only %s" % (
                "class" if decl.is_class else "instance", kind)
            plans.append(p)
            continue
        # struct capability checks
        bad = None
        for a, par in zip(args, decl.params):
            if a in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[a], _EMPTY_CAPS).to_segment:
                bad = "no toSegment() for " + STRUCT_JAVA[a]
        if ret in STRUCT_JAVA and not wrappers.get(STRUCT_JAVA[ret], _EMPTY_CAPS).from_segment:
            bad = "no fromSegment() for " + STRUCT_JAVA[ret]
        if ret == "TRANSFORM3D" and not (wrappers.get("CATransform3D") and wrappers["CATransform3D"].slot):
            bad = "no slot() for CATransform3D"
        if bad:
            p.skip, p.reason = True, bad
            plans.append(p)
            continue
        # duplicate Java name: keep the first (deterministic because decls are ordered)
        if p.java_name in seen_names:
            p.skip, p.reason = True, "duplicate Java name (first declared wins)"
            plans.append(p)
            continue
        seen_names[p.java_name] = sel
        p.ret_kind, p.ret_java = classify_ret_java(
            ret, decl.ret_raw, wrappers, cls_name, toks[0] if toks else None)
        for i, (a, par) in enumerate(zip(args, decl.params)):
            tok = toks[3 + i] if 3 + i < len(toks) else None
            k, jt = classify_param_java(a, par.type_raw, par.name, wrappers, cls_name, tok)
            p.params.append((k, jt, param_name(par.name, i)))
        p.handle = "h_" + ret + "".join("_" + a for a in args)
        plans.append(p)
    return plans


def apply_skip_gates(plans, include_deprecated=True):
    """Blacklist / feature gates applied before touching the runtime."""
    return plans


# ------------------------------------------------------------------ rendering

def render_method(p, class_name):
    d, shape = p.decl, p.shape
    ret, args = shape
    recv = 'ObjC.cls("%s")' % class_name if p.is_class else "peer"
    params = ", ".join("%s %s" % (jt, nm) for _k, jt, nm in p.params)
    args_java = []
    for (k, _jt, nm) in p.params:
        if k == "id":
            args_java.append(nm)
        elif k == "string":
            # The explicit cast is load-bearing (same as the hand-written wrappers):
            # without it javac types the conditional as Object and invokeExact rejects it.
            args_java.append("(MemorySegment) (%s == null ? MemorySegment.NULL : ObjC.nsstring(%s))" % (nm, nm))
        elif k.startswith("typed:"):
            args_java.append("(MemorySegment) (%s == null ? MemorySegment.NULL : %s.peer())" % (nm, nm))
        elif k in ("long", "boolean", "double", "float", "byte", "int", "short"):
            args_java.append(nm)
        elif k == "uint32":
            args_java.append("(int) " + nm)
        else:
            args_java.append("%s.toSegment()" % nm)
    call_args = ", ".join([recv, "Sels." + p.field] + args_java)
    alloc = None
    if ret in STRUCT_JAVA:
        alloc = "CATransform3D.slot()" if ret == "TRANSFORM3D" else "ObjC.structSlot()"
    static = "static " if p.is_class else ""
    lines = []
    dep = " (deprecated)" if d.deprecated else ""
    lines.append("    /// %s%s - generated from %s." % (d.selector, dep, d.raw[:90]))
    lines.append("    public %s%s %s(%s) {" % (static, p.ret_java, p.java_name, params))
    lines.append("        ensureInit();")
    lines.append("        try {")
    if ret == "VOID":
        lines.append("            H.%s().invokeExact(%s);" % (p.handle, call_args))
    elif ret == "INT32" and p.ret_kind == "uint32":
        # uint32_t return: read exactly 32 bits, then zero-extend into the long surface
        # (the house form in MTLStencilDescriptor.readMask).
        lines.append("            return ((int) H.%s().invokeExact(%s)) & 0xFFFFFFFFL;"
                     % (p.handle, call_args))
    elif ret in SCALAR_JAVA:
        # The cast is the exact-width read: INT32 is a 4-byte JAVA_INT handle, SHORT a
        # 2-byte JAVA_SHORT one, INT the 64-bit C-long class.  Widening an int return to
        # long without the cast would read 64 bits of a 32-bit write.
        cast = {"INT": "long", "BOOL": "boolean", "DOUBLE": "double", "FLOAT": "float",
                "BYTE": "byte", "INT32": "int", "SHORT": "short"}[ret]
        lines.append("            return (%s) H.%s().invokeExact(%s);" % (cast, p.handle, call_args))
    elif ret in STRUCT_JAVA:
        lines.append("            MemorySegment seg = (MemorySegment) H.%s().invokeExact(%s, %s);"
                     % (p.handle, alloc, call_args))
        lines.append("            return %s.fromSegment(seg);" % STRUCT_JAVA[ret])
    else:  # ID
        lines.append("            MemorySegment r = (MemorySegment) H.%s().invokeExact(%s);"
                     % (p.handle, call_args))
        if p.ret_kind == "string":
            lines.append("            return ObjC.toString(r);")
        elif p.ret_kind == "typed":
            lines.append("            return %s.wrap(r);" % p.ret_java)
        else:
            lines.append("            return r;")
    lines.append("        } catch (Throwable t) { throw new RuntimeException(\"%s failed\", t); }" % d.selector)
    lines.append("    }")
    return "\n".join(lines)


def render_class(class_name, superclass, header_rel, plans, iface, framework="AppKit"):
    used = [p for p in plans if not p.skip]
    handles = OrderedDict()
    for p in sorted(used, key=lambda q: (q.shape[0], q.shape[1])):
        handles[p.handle] = p.shape
    fields = OrderedDict()
    for p in sorted(used, key=lambda q: q.field):
        fields[p.field] = p.decl.selector

    L = []
    L.append(MARKER)
    L.append("package nsui;")
    L.append("")
    L.append("import java.lang.foreign.MemorySegment;")
    if handles:
        L.append("import java.lang.invoke.MethodHandle;")
    L.append("")
    L.append("import nsui.objc.ObjC;")
    L.append("import nsui.objc.Sig;")
    L.append("import static nsui.objc.Sig.Arg;")
    L.append("import static nsui.objc.Sig.Ret;")
    L.append("")
    L.append("/// %s - generated wrapper (CodeGen %s) from %s." % (class_name, VERSION, header_rel))
    L.append("///")
    L.append("/// %d methods generated from the ObjC runtime type encoding; every shape is in" % len(used))
    L.append("/// Sig.VOCABULARY and is checked by tests/SignatureConformanceTest. Do not edit")
    L.append("/// by hand: rerun out/codegen/gen.py and apply the emitted patch.")
    skipped = [p for p in plans if p.skip]
    if skipped:
        L.append("///")
        L.append("/// Omitted (%d): %s" % (len(skipped),
                 ", ".join(sorted(set(p.reason for p in skipped)))))
    L.append("public class %s extends %s {" % (class_name, superclass))
    L.append("")
    # selectors
    L.append("    /// Cached selectors, populated once from ensureInitLocked().")
    L.append("    private static final class Sels {")
    for f in fields:
        L.append("        static MemorySegment %s;" % f)
    L.append("        static void populate() {")
    for f, sel in fields.items():
        L.append("            %s = ObjC.sel(\"%s\");" % (f, sel))
    L.append("        }")
    L.append("    }")
    L.append("")
    # handles
    if handles:
        comps = ", ".join("MethodHandle %s" % h for h in handles)
        L.append("    private record Handles(%s) {}" % comps)
        L.append("    private static volatile Handles H;")
        L.append("")
    L.append("    protected %s(MemorySegment peer) {" % class_name)
    L.append("        super(peer);")
    L.append("        ensureInit();")
    L.append("    }")
    L.append("")
    L.append("    /// Wrap an id as %s (null for nil)." % class_name)
    L.append("    public static %s wrap(MemorySegment peer) {" % class_name)
    L.append("        return (peer == null || peer.address() == 0) ? null : new %s(peer);" % class_name)
    L.append("    }")
    L.append("")
    L.append("    private static void ensureInit() {")
    L.append("        if (H != null) return;")
    L.append("        ensureInitLocked();")
    L.append("    }")
    L.append("")
    L.append("    private static synchronized void ensureInitLocked() {")
    L.append("        if (H != null) return;")
    fw = "QuartzCore" if class_name.startswith(("CA", "MTL")) else (framework or "AppKit")
    L.append("        try { ObjC.ensureFramework(\"%s\"); } catch (Throwable ignored) {}" % fw)
    if handles:
        L.append("        Handles h = new Handles(")
        for i, h in enumerate(handles):
            sh = handles[h]
            sig = "Sig.of(Ret.%s%s)" % (sh[0], "".join(", Arg.%s" % a for a in sh[1]))
            comma = "," if i < len(handles) - 1 else ");"
            L.append("                ObjC.handle(%s)%s" % (sig, comma))
    L.append("        Sels.populate();")
    if handles:
        L.append("        H = h;")
    L.append("    }")
    L.append("")
    for p in sorted(used, key=lambda q: (q.is_class, q.java_name)):
        L.append(render_method(p, class_name))
        L.append("")
    L.append("}")
    return "\n".join(L) + "\n"


# ------------------------------------------------------------------ patch/apply

def _git_diff_trees(pending, scratch):
    if os.path.isdir(scratch):
        shutil.rmtree(scratch)
    os.makedirs(scratch)
    a = os.path.join(scratch, "a")
    b = os.path.join(scratch, "b")
    # Both roots must exist even when one side is empty: a new-file-only patch
    # has no "a" entries at all, and git refuses a missing path.
    os.makedirs(a, exist_ok=True)
    os.makedirs(b, exist_ok=True)
    for rel, base_text, new_text in pending:
        pa = os.path.join(a, rel)
        pb = os.path.join(b, rel)
        if base_text is not None:
            os.makedirs(os.path.dirname(pa), exist_ok=True)
            with open(pa, "w", encoding="utf-8") as fh:
                fh.write(base_text)
        os.makedirs(os.path.dirname(pb), exist_ok=True)
        with open(pb, "w", encoding="utf-8") as fh:
            fh.write(new_text)
    proc = subprocess.run(["git", "diff", "--no-index", "--no-color",
                           "--src-prefix=", "--dst-prefix=", "a", "b"],
                          cwd=scratch, capture_output=True, text=True)
    return proc.stdout


def make_patch(repo, plan, scratch):
    pending = []
    for rel, new_text in plan:
        path = os.path.join(repo, rel)
        base = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                base = fh.read()
        if base == new_text:
            continue
        pending.append((rel, base, new_text))
    text = _git_diff_trees(pending, scratch) if pending else ""
    return text, pending


def apply_plan(repo, pending):
    written = []
    unchanged = []
    for rel, _base, new_text in pending:
        path = os.path.join(repo, rel)
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                if fh.read() == new_text:
                    unchanged.append(rel)
                    continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new_text)
        written.append(rel)
    return written, unchanged


# ---------------------------------------------------------------- survey mode

def find_sdk():
    try:
        p = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True)
        p = (p.stdout or "").strip()
        if p and os.path.isdir(p):
            return p
    except Exception:
        pass
    for cand in ("/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk",):
        if os.path.isdir(cand):
            return cand
    raise SystemExit("no macOS SDK found (xcrun --show-sdk-path failed)")


def framework_headers_dir(sdk, fw):
    return os.path.join(sdk, "System", "Library", "Frameworks", fw + ".framework", "Headers")


def find_header(sdk, cls, frameworks):
    for fw in frameworks:
        root = framework_headers_dir(sdk, fw)
        if not os.path.isdir(root):
            continue
        for dirpath, _dirs, files in os.walk(root):
            for fn in sorted(files):
                if not fn.endswith(".h"):
                    continue
                path = os.path.join(dirpath, fn)
                try:
                    ifaces = hdrs.parse_file(path)
                except Exception:
                    continue
                for iface in ifaces:
                    if iface.kind == "interface" and not iface.category and iface.name == cls:
                        return path, fw, iface
    return None, None, None


def _out_param(p):
    if p.is_out:
        return True
    return bool(re.match(r"^\s*(id|NSError|NSRect|CGRect|NSPoint|CGPoint|NSSize|CGSize|"
                         r"NSRange|CGFloat|NSInteger|NSUInteger|BOOL|double|float|int|long|"
                         r"NSRectEdge)\s*\*+\s*$", p.type_raw or ""))


def survey(frameworks, args):
    sdk = find_sdk()
    rt = objcabi.ObjCRuntime(list(frameworks))
    repo = os.path.abspath(args.repo)
    vocab = load_vocabulary(os.path.join(repo, "src", "nsui", "objc", "Sig.java"))
    c = {}
    examples = {}
    shapes = {}
    newshapes = {}
    structs = {}

    def bump(k, n=1):
        c[k] = c.get(k, 0) + n

    def ex(reason, s):
        L = examples.setdefault(reason, [])
        if len(L) < 8:
            L.append(s)

    seen = set()
    for fw in frameworks:
        for iface in hdrs.parse_framework(sdk, fw, include_categories=True):
            bucket = ("protocol" if iface.kind == "protocol"
                      else ("category" if iface.category else "class"))
            bump(bucket + "_bodies")
            bump(bucket + "_bodies:" + fw)
            for d in iface.decls:
                bump("decls")
                bump(bucket + "_decls")
                if d.kind == "method":
                    bump("methods")
                if d.property:
                    bump("property_accessors")
                if d.is_class:
                    bump("class_methods")
                if d.multiline:
                    bump("multiline_decls")
                if any(p.is_block for p in d.params):
                    bump("decls_with_block_param")
                if any(_out_param(p) for p in d.params):
                    bump("decls_with_out_param")
                if any(p.is_generic for p in d.params) or "<" in d.ret_raw:
                    bump("decls_with_generics")
                if "..." in d.raw:
                    bump("decls_variadic")
                if d.deprecated:
                    bump("decls_deprecated")
                if d.unavailable:
                    bump("decls_unavailable")
                key = (d.owner, d.selector, d.is_class)
                if key in seen:
                    bump("duplicate_decls")
                    continue
                seen.add(key)
                enc, kind = rt.encoding(d.owner, d.selector)
                if enc is None:
                    bump("unresolved")
                    bump("unresolved_" + kind)
                    bump(bucket + "_unresolved_" + kind)
                    ex(kind, "%s %s%s" % (d.owner, "-" if not d.is_class else "+", d.selector))
                    continue
                bump("resolved")
                if (d.is_class and kind != "class") or (not d.is_class and kind != "inst"):
                    bump("kind_mismatch")
                    bump("kind_mismatch_" + bucket)
                shape = objcabi.shape_of(enc)
                if shape is None:
                    bump("unparseable_encoding")
                    continue
                shapes[shape] = shapes.get(shape, 0) + 1
                if shape in vocab:
                    bump(bucket + "_in_vocab")
                else:
                    bump(bucket + "_new_shape")
                    newshapes[shape] = newshapes.get(shape, 0) + 1
                for tok in objcabi.parse_types(enc):
                    if tok.startswith("{"):
                        nm = objcabi.struct_name(tok)
                        sz = objcabi.struct_bytes(tok)
                        structs[(nm, sz)] = structs.get((nm, sz), 0) + 1

    L = []
    L.append("CodeGen %s survey - %s" % (VERSION, ", ".join(frameworks)))
    L.append("SDK: %s" % sdk)
    L.append("")
    L.append("-- declarations parsed --")
    for k in ("class_bodies", "category_bodies", "protocol_bodies", "decls", "methods",
              "property_accessors", "class_methods", "duplicate_decls"):
        L.append("  %-28s %d" % (k, c.get(k, 0)))
    L.append("")
    L.append("-- features (of %d distinct decls) --" % len(seen))
    for k in ("multiline_decls", "decls_with_block_param", "decls_with_out_param",
              "decls_with_generics", "decls_variadic", "decls_deprecated",
              "decls_unavailable"):
        L.append("  %-28s %d" % (k, c.get(k, 0)))
    L.append("")
    L.append("-- runtime resolution --")
    L.append("  %-28s %d" % ("resolved", c.get("resolved", 0)))
    L.append("  %-28s %d" % ("unresolved", c.get("unresolved", 0)))
    for k in sorted(c):
        if k.startswith("unresolved_"):
            L.append("  %-28s %d" % (k, c[k]))
    L.append("  %-28s %d" % ("kind_mismatch", c.get("kind_mismatch", 0)))
    L.append("")
    L.append("-- shape split (distinct selectors by declaration site) --")
    for b in ("class", "category", "protocol"):
        iv, nv = c.get(b + "_in_vocab", 0), c.get(b + "_new_shape", 0)
        un = sum(v for k, v in c.items() if k.startswith(b + "_unresolved_"))
        L.append("  %-9s in Sig.VOCABULARY: %-6d needs new shape: %-6d  unresolved: %-6d"
                 % (b, iv, nv, un))
    L.append("  distinct shapes seen: %d   in vocabulary: %d   new: %d"
             % (len(shapes), len([s for s in shapes if s in vocab]),
                len([s for s in shapes if s not in vocab])))
    L.append("")
    L.append("-- top new Sig shapes (class/category only) --")
    cls_new = {}
    for s, n in newshapes.items():
        cls_new[s] = n
    for s, n in sorted(cls_new.items(), key=lambda kv: -kv[1])[:25]:
        L.append("  %-6d of(Ret.%s%s)" % (n, s[0], "".join(", Arg.%s" % a for a in s[1])))
    L.append("")
    L.append("-- struct tokens by size --")
    big = [(k, v) for k, v in structs.items() if (k[1] or 0) > 16]
    small = [(k, v) for k, v in structs.items() if (k[1] or 0) <= 16]
    L.append("  distinct <=16B: %d   distinct >16B: %d" % (len(small), len(big)))
    for (nm, sz), n in sorted(big, key=lambda kv: -kv[1])[:20]:
        L.append("  %-34s %4s bytes  x%d" % (nm, sz, n))
    L.append("")
    L.append("-- failure examples --")
    for reason in sorted(examples):
        for s in examples[reason]:
            L.append("  %-22s %s" % (reason, s))
    text = "\n".join(L) + "\n"
    report_txt = os.path.join(os.path.dirname(os.path.abspath(__file__)), "survey.txt")
    report_json = os.path.join(os.path.dirname(os.path.abspath(__file__)), "survey.json")
    with open(report_txt, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(report_json, "w", encoding="utf-8") as fh:
        json.dump({"counters": c, "examples": examples,
                   "new_shapes": [{"ret": s[0], "args": list(s[1]), "count": n}
                                  for s, n in sorted(newshapes.items(), key=lambda kv: -kv[1])],
                   "structs_over_16": [{"name": k[0], "bytes": k[1], "count": v}
                                       for k, v in sorted(structs.items(), key=lambda kv: -(kv[0][1] or 0))]},
                  fh, indent=1, sort_keys=True)
    print(text)
    return 0


