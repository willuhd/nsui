def resolve_inherited_names(plans, effective, superclass):
    """Apply every inherited-signature decision to `plans` in place, returning report lines.

    Shared with the tooling (codegen/probe.py enumerates calls from the plans), because a caller
    that plans a class on its own has to see the same Java names the generator will emit —
    otherwise it synthesizes calls to methods that were renamed or skipped.
    """
    notes = []
    inherited = inherited_members(effective, superclass)
    used_names = {q.java_name for q in plans if not q.skip}
    for q in plans:
        if q.skip:
            continue
        forms = [f for f in inherited.get(q.java_name, []) if f[0] == len(q.params)]
        if not forms:
            continue
        is_static, ret = forms[0][1], forms[0][2]
        note = None
        renamed = False
        if is_static == q.is_class:
            # The target tree already provides this member on an ancestor, so emitting it again
            # would only duplicate an inherited API. This is the general replacement for the old
            # per-name blacklist of hash/copy/description/isKindOfClass: and friends.
            q.skip = True
            q.reason = "already provided by an inherited wrapper"
            note = "SKIP %s  [inherited from a shipped wrapper]" % q.java_name
        elif is_static != q.is_class:
            before = q.java_name
            q.java_name += "Class" if q.is_class else "Instance"
            renamed = True
            note = "RENAMED %s -> %s   [static/instance clash with an inherited member]" % (
                before, q.java_name)
        elif ret != q.ret_java:
            if ret == "MemorySegment":
                q.ret_kind, before = "id", q.ret_java
                q.ret_java = ret
                note = "RETYPED %s: %s -> MemorySegment   [inherited signature wins]" % (
                    q.java_name, before)
            elif ret in effective:
                q.ret_kind, before = "typed", q.ret_java
                q.ret_java = ret
                note = "RETYPED %s: %s -> %s   [inherited signature wins]" % (
                    q.java_name, before, ret)
            else:
                before = q.java_name
                q.java_name += "Own"
                renamed = True
                note = "RENAMED %s -> %s   [return type differs from the inherited member]" % (
                    before, q.java_name)
        if note:
            if renamed:
                while q.java_name in used_names:
                    q.java_name += "_"
                used_names.add(q.java_name)
            notes.append(note)
    return notes


def plan_class(cls, frameworks, sdk, vocab, wrappers, rt, toolkit=None, include_deprecated=True):
    """Everything the generator decides for one class, in one place.

    Tools that need the same view (probe.py enumerating calls, a future conformance checker) get
    the post-rename plans this way instead of re-deriving the naming rules.
    """
    surface = collect_surface(cls, frameworks, sdk)
    if surface is None:
        return None
    effective = dict(wrappers)
    superclass = surface.superclass if surface.superclass in effective else "NSObject"
    plans = build_plan(surface, rt, vocab, effective, cls, include_deprecated=include_deprecated,
                       toolkit=toolkit)
    notes = resolve_inherited_names(plans, effective, superclass)
    return {"surface": surface, "superclass": superclass, "plans": plans, "notes": notes,
            "effective": effective}


def gen_classes(args, sdk, vocab, wrappers, rt):
    files = []
    lines = []
    new_shape_counter = {}
    vocab_needed = []
    protected_init = subclasses_using_init(wrappers)
    toolkit = Toolkit(getattr(args, "repo", "."))
    evidence, evidence_path = load_guard_evidence(getattr(args, "guard_evidence", None))
    shipped_verdicts = load_shipped_baseline(getattr(args, "shipped_baseline", None))
    if evidence:
        lines.append("NOTE guard evidence: %s (%d case(s))"
                     % (os.path.basename(evidence_path),
                        sum(len(v) for v in evidence.values())))
    missing_primitives = toolkit.missing()
    if missing_primitives:
        lines.append("NOTE target tree lacks: %s" % ", ".join(missing_primitives))
    # Oracle stubs (R11-13): report-only verification of the tables emission takes
    # on faith. A mismatch names the table and the expectation; emission is unchanged
    # (a wrong literal still miscompiles loudly at merge time via compile_verify).
    lines.extend(check_oracle_tables(getattr(args, "repo", ".")))
    surfaces = OrderedDict()
    for cls in args.classes:
        surface = collect_surface(cls, args.frameworks, sdk)
        if surface is None:
            lines.append("SKIP %s: no @interface in %s" % (cls, ", ".join(args.frameworks)))
            continue
        surfaces[cls] = surface
    # A class this run will create is as available to the type mapper as one already in the tree —
    # but only if it really will be written. A whole-class drop (unextendable superclass) has to
    # propagate: in the 2026-08-20 tree NSPanel is dropped because NSWindow is final there, and
    # without this fixpoint NSSavePanel still emitted `extends NSPanel` against a file that was
    # never written (73 cascading "cannot find symbol: peer" errors). Iterating to a stable set is
    # bounded by the number of requested classes.
    dropped = {}
    supers = {}
    while True:
        effective = dict(wrappers)
        effective.update({c: PendingCaps(c) for c in surfaces
                          if c not in wrappers and c not in dropped})
        changed = False
        for cls, surface in surfaces.items():
            if cls in dropped:
                continue
            superclass = surface.superclass if surface.superclass in effective else "NSObject"
            supers[cls] = superclass
            is_protocol_surface = bool(surface.parts) \
                and surface.parts[0][0].kind == "protocol"
            if surface.superclass is None and cls != "NSObject" and not is_protocol_surface:
                # NSProxy is a root class in the SDK (its `<NSObject>` is a protocol list, not a
                # superclass). Emitting `extends NSObject` compiled but described the wrong
                # hierarchy, and the generated template needs the hand-written base for `peer`.
                # A protocol has no superclass by definition and is not a root class: the generator
                # wraps protocol surfaces on purpose (the Metal device/buffer families are
                # @protocol). Applying this rule to them dropped 46 of Foundation's 53.
                dropped[cls] = ("the SDK declares no superclass; a root class needs the "
                                "hand-written NSObject base")
                changed = True
                continue
            if superclass == cls:
                # The hierarchy root is hand-written: a generated `class NSObject extends NSObject`
                # is both a compile error and missing the `peer` field every subclass uses. Drop it
                # so the shipped root stays in place for its dependents.
                dropped[cls] = "the hierarchy root is hand-written (it would extend itself)"
                changed = True
                continue
            if not toolkit.can_extend(superclass, effective):
                dropped[cls] = ("target wrapper %s cannot be extended (final or private constructor)"
                                % superclass)
                changed = True
        if not changed:
            break
    for cls in surfaces:
        if cls in dropped:
            lines.append("SKIP %s: %s" % (cls, dropped[cls]))
    for cls, surface in surfaces.items():
        if cls in dropped:
            continue
        superclass = supers[cls]
        plans = build_plan(surface, rt, vocab, effective, cls,
                           include_deprecated=not args.skip_deprecated, toolkit=toolkit)
        used = [p for p in plans if not p.skip]
        skipped = [p for p in plans if p.skip]
        lines.extend(resolve_inherited_names(plans, effective, superclass))
        # Guards the evidence asks for. A missing helper in the target tree, a parameter the
        # header named differently or a case that needs a class-local guard all show up as a
        # report line rather than a silently dropped guard.
        for q in plans:
            if q.skip:
                continue
            for case in evidence.get((cls, q.decl.selector), []):
                wanted = case.get("guards") or []
                already_reported = False
                if case.get("needs_local_guard"):
                    lines.append("    GUARD-LOCAL %s%s  [%s]" % (
                        "+" if q.is_class else "", q.decl.selector,
                        str(case["needs_local_guard"])[:70]))
                    continue
                shipped = shipped_verdicts.get(case.get("probe_id"))
                # One helper, one rule (see resolve_guard_target): name first, then
                # the stable param_index fallback.
                target = resolve_guard_target(q.params, case)
                if q.is_class:
                    lines.append("    GUARD-SKIPPED %s+  [evidence case is an instance call]" %
                                 q.decl.selector)
                    continue
                if target is None:
                    lines.append("    GUARD-MISS %s  [no parameter named %s]" % (
                        q.decl.selector, case.get("param")))
                    continue
                # R2: the parameter kind, for struct decomposition (viewport needs 6
                # component guards; a single finite does not compile for a struct param).
                target_kind = next((k for k, _jt, nm in q.params if nm == target), None)
                # R2: expand the R1 single-finite scaffolding to the compilable 6x form.
                # The evidence row stores one finite; the emitter needs six + null-first.
                if target_kind == "mtlviewport" and case.get("badness") == "inf" and wanted:
                    # Only the single form needs expanding; a row that already stores the
                    # decomposition (future probe with param_kind) passes through unchanged.
                    if not any(".originX()" in g for g in wanted):
                        wanted = struct_decomposition("mtlviewport", "{p}", q.decl.selector)
                        lines.append("    GUARD-DECOMPOSED %s%s  [viewport INF expands to 6x finite "
                                     "null-first]" % ("+" if q.is_class else "", q.decl.selector))
                # A stored single nonNegative for a scissor rect expands the same way:
                # the evidence row keeps one guard, the emitter needs four + null-first.
                if target_kind == "mtlscissorrect" and case.get("badness") == "negative" and wanted:
                    if not any(".x()" in g for g in wanted):
                        wanted = struct_decomposition("mtlscissorrect", "{p}", q.decl.selector)
                        lines.append("    GUARD-DECOMPOSED %s%s  [scissor negative expands to 4x "
                                     "nonNegative null-first]" % ("+" if q.is_class else "",
                                                                  q.decl.selector))
                if not wanted and case.get("control") and shipped in (
                        "java-exception", "objc-abort", "sigtrap", "sigill"):
                    # Measured: the generated wrapper tolerates an argument the shipped wrapper
                    # rejects. Matching it is conformance, not extra strictness.
                    wanted = guard_template(case, target_kind)
                    if wanted:
                        lines.append("    GUARD-MATCH %s%s  [the shipped wrapper rejects this "
                                     "argument]" % ("+" if q.is_class else "", q.decl.selector))
                        already_reported = True
                if shipped == "tolerated":
                    # Measured: the shipped wrapper accepts this argument, so a guard here would be
                    # stricter than the code it replaces. For nil its own body must be skipping the
                    # send (a nil aborts natively), so match that with an early return.
                    struct_ret = q.ret_java in STRUCT_JAVA.values()
                    if (case.get("badness") == "nil" and struct_ret
                            and is_sentinel_family(cls, q.decl.selector, q.ret_java)):
                        # A nil search input means "not found", never a zero geometry: take the
                        # family sentinel, and refuse loudly (keep the guard, no early return)
                        # when no override exists rather than emitting a silently wrong zero.
                        sentinel = NSRANGE_SEARCH_SENTINEL.get(q.decl.selector)
                        if sentinel:
                            if target not in q.nil_skips:
                                q.nil_skips.append(target)
                            q.nil_returns[target] = sentinel
                            lines.append("    NIL-SKIP %s%s  [the shipped wrapper tolerates nil; "
                                         "search sentinel]" % ("+" if q.is_class else "",
                                                               q.decl.selector))
                        else:
                            lines.append("    NIL-SENTINEL-MISSING %s%s  [nil-tolerated NSRange "
                                         "search needs a NOT_FOUND override, refusing NIL-SKIP]"
                                         % ("+" if q.is_class else "", q.decl.selector))
                            lines.append("    GUARD-SKIPPED %s%s  [the shipped wrapper tolerates "
                                         "this argument]" % ("+" if q.is_class else "",
                                                              q.decl.selector))
                        continue
                    default = (struct_default(q.ret_java, getattr(args, "repo", "."))
                               if struct_ret else "null")
                    if case.get("badness") == "nil" and (not struct_ret or default):
                        if target not in q.nil_skips:
                            q.nil_skips.append(target)
                        if struct_ret:
                            # The renderer inlines this instead of assuming .ZERO, so
                            # ZERO-less structs (Metal value types, CATransform3D) compile.
                            # Search-family sentinels are handled above (nil_returns already
                            # carries NOT_FOUND); the generic default stays for the rest.
                            q.nil_returns[target] = default
                        lines.append("    NIL-SKIP %s%s  [the shipped wrapper tolerates nil]"
                                     % ("+" if q.is_class else "", q.decl.selector))
                    else:
                        lines.append("    GUARD-SKIPPED %s%s  [the shipped wrapper tolerates this "
                                     "argument]" % ("+" if q.is_class else "", q.decl.selector))
                    continue
                if not wanted:
                    continue
                if any("Bounds.index" in g for g in wanted) and case.get("bound"):
                    repo_ = getattr(args, "repo", ".")
                    if not bound_is_usable(case["bound"], plans, repo_, cls):
                        # A corpus bound may be a self-contained accessor (`numberOfItems()`) or use
                        # a local the shipped method declares just above the guard. The second form
                        # needs that declaration copied with it; anything else cannot be emitted.
                        setup = shipped_index_setup(q.decl.selector, case["bound"], repo_, cls)
                        if setup:
                            for stmt in setup:
                                if stmt not in q.guard_setup:
                                    q.guard_setup.append(stmt)
                            lines.append("    GUARD-BOUND-SETUP %s%s  [copied %s from the shipped "
                                         "method]" % ("+" if q.is_class else "", q.decl.selector,
                                                      ", ".join(setup)[:60]))
                        else:
                            lines.append("    GUARD-UNUSABLE-BOUND %s%s  [%s does not resolve on the "
                                         "generated class]" % ("+" if q.is_class else "",
                                                               q.decl.selector, case["bound"]))
                            continue
                    else:
                        # A bare per-selector maximum travels as a class-level constant: qualify
                        # the reference and copy the declaration (guard_setup renders inside
                        # method bodies, so a field needs its own channel — see class_consts).
                        b = (case.get("bound") or "").strip()
                        decl = shipped_declares_max(repo_, cls, b) if re.fullmatch(
                            r"MAX_[A-Z0-9_]+", b) else None
                        if decl:
                            wanted = [re.sub(r"\b%s\b" % re.escape(b), cls + "." + b, g)
                                      for g in wanted]
                            if decl not in q.class_consts:
                                q.class_consts.append(decl)
                            lines.append("    GUARD-CONST %s%s  [copied %s from the shipped "
                                         "class]" % ("+" if q.is_class else "", q.decl.selector,
                                                     decl[:60]))
                need = [g.split("(")[0] for g in wanted]
                missing = [n for n in need if n in PRIMITIVES and not toolkit.has(n)]
                if missing:
                    lines.append("    GUARD-UNAVAILABLE %s  [target tree lacks %s]" % (
                        q.decl.selector, ", ".join(missing)))
                    continue
                # A selector can carry a guard per index parameter (cellAtColumnIndex:rowIndex:
                # needs both), so these accumulate: assigning meant the second replaced the first.
                q.guard_setup.extend(case.get("setup") or [])
                q.guards.extend(g.replace("{p}", target) for g in wanted)
                if already_reported:
                    continue          # reported as a match; its guard is in the list once
                lines.append("    GUARD %s%s  [measured %s]" % (
                    "+" if q.is_class else "", q.decl.selector, case.get("unguarded")))
            # R2: type-driven struct policy. The probe now synthesizes a negative-width
            # scissor candidate, but no evidence row is measured yet; negatives are still
            # always caller errors (live: neg-w aborts 134 with validation, finite
            # tolerated, huge target-dependent so only nonNegative is safe). Emit 4x
            # nonNegative null-first whenever the method takes a scissor rect and has no
            # guard for it yet, so the generated wrapper matches the hand-written one
            # without a per-class exception. Once a negative row is measured the evidence
            # path above (GUARD-DECOMPOSED) takes over and this is skipped as guarded.
            # Viewport is evidence-driven (R1 row) and already decomposed above; if a future
            # viewport method arrives with no evidence, the same type policy would apply, but
            # emitting it unconditionally would hide a missing measurement, so only scissor
            # (whose only candidate is the new negative form) is unconditional here.
            for k, _jt, nm in q.params:
                if k != "mtlscissorrect" or q.is_class:
                    continue
                if any(re.search(r"\b%s\b" % re.escape(nm), g) for g in q.guards):
                    continue
                dec = struct_decomposition("mtlscissorrect", nm, q.decl.selector)
                need = [g.split("(")[0] for g in dec]
                if any(n in PRIMITIVES and not toolkit.has(n) for n in need):
                    lines.append("    GUARD-UNAVAILABLE %s  [target tree lacks %s]" % (
                        q.decl.selector, ", ".join(need)))
                    continue
                q.guards.extend(dec)
                lines.append("    GUARD-TYPE %s%s  [scissor 4x nonNegative null-first]" % (
                    "+" if q.is_class else "", q.decl.selector))
            # Type-driven uint32 range policy. A uint32_t parameter is carried in a Java long
            # and narrowed with (int) at the call, so a value outside 0..4294967295 silently
            # wraps (bit 31 set goes negative; high bits are lost) instead of failing loudly.
            # The shipped wrappers guard this inline (MTLStencilDescriptor.setReadMask:, the
            # stencil setters, clearStencil:); the generator emitted the same (int) cast with
            # no guard, so regenerating one of those classes stripped the shipped check.
            # Emit the same inline range check for every uint32 parameter with no guard yet.
            for k, _jt, nm in q.params:
                if k != "uint32":
                    continue
                # Match the guard statement itself (`if (<nm> < 0`), not a bare name search:
                # the message embeds the selector, and a multi-param selector
                # (`setStencilFrontReferenceValue:backReferenceValue:`) contains the second
                # parameter's name, so a substring test falsely read the first guard as
                # covering the second and left it unguarded.
                if any(re.search(r"if\s*\(\s*%s\s*<" % re.escape(nm), g) for g in q.guards):
                    continue
                q.guards.extend([
                    'if (%s < 0 || %s > 0xFFFFFFFFL) {' % (nm, nm),
                    '    throw new IllegalArgumentException("%s %s " + %s + " out of range '
                    '(0..4294967295)");' % (q.decl.selector, nm, nm),
                    '}'])
                lines.append("    GUARD-TYPE %s%s  [uint32 range 0..4294967295 for %s]" % (
                    "+" if q.is_class else "", q.decl.selector, nm))
        # Emitter nan/inf union: a scalar carrying both notNaN (nan case) and finite
        # (inf case or GUARD-MATCH control) keeps finite only — finite already rejects
        # NaN, so the pair is one policy, not two. Runs after every guard source above
        # (evidence, GUARD-MATCH, scissor type policy) so no path reintroduces the pair.
        for r in plans:
            if r.skip or not r.guards:
                continue
            kept, dropped = union_nan_inf_guards(r.guards)
            if dropped:
                r.guards = kept
                lines.append("    GUARD-UNION %s%s  [finite subsumes notNaN for %s]" % (
                    "+" if r.is_class else "", r.decl.selector, ", ".join(dropped)))
        # A member typed by a class this same run creates is not reproducible by a later run that
        # generates only this class (the other file may be missing): say so rather than let the
        # output drift silently between a batch and an incremental regeneration.
        pending_types = sorted(
            {q.ret_java for q in plans if not q.skip and q.ret_java in effective
             and q.ret_java not in wrappers}
            | {jt for q in plans if not q.skip for k, jt, _n in q.params
               if k.startswith("typed:") and jt in effective and jt not in wrappers})
        if pending_types:
            lines.append("    NOTE typed by classes this run creates: %s" % ", ".join(pending_types))
        target = os.path.join(getattr(args, "repo", "."), "src", "nsui", cls + ".java")
        existing_text = ""
        if os.path.exists(target):
            existing_text = open(target, encoding="utf-8", errors="replace").read()
        rel_header = os.path.relpath(surface.file, sdk)
        # A class that declares no initializer gets no factory. Fabricating one from the inherited
        # -init looked helpful — it made NSByteCountFormatter constructible — until a smoke test
        # built a CAMetalDisplayLink that way and `isPaused()` aborted the JVM: an object from the
        # wrong initializer is not an object, and a crash is worse than "not constructible". Every
        # SDK initializer here is unmarked (no NS_DESIGNATED_INITIALIZER in these headers), so there
        # is no signal to pick the right one, and guessing is what this exercise avoids. The corpus
        # hand-writes create() per class for exactly this reason.
        if not any(getattr(q, "is_constructor", False) for q in plans if not q.skip) \
                and not (bool(surface.parts) and surface.parts[0][0].kind == "protocol"):
            lines.append("    NOTE declares no initializer; no factory is emitted (the corpus "
                         "hand-writes create())")
        text = render_class(cls, superclass, rel_header, plans, surface, surface.framework,
                            protected_init=cls in protected_init
                            or parent_init_visible(effective, superclass))
        before = set(re.findall(r"public\s+(?:static\s+)?[\w.<>\[\]]+\s+(\w+)\s*\(",
                                existing_text)) if existing_text else set()
        after = {q.java_name for q in plans if not q.skip} | set(
            re.findall(r"public\s+(?:static\s+)?[\w.<>\[\]]+\s+(\w+)\s*\(", text))
        still = sorted(before - after)
        if still and existing_text and MARKER not in existing_text:
            types, fields, inits, methods = hand_written_parts(existing_text, text)
            pieces = types + fields + methods
            merged, reason = text, "nothing mergeable"
            if pieces or inits:
                body = text.rstrip()
                if body.endswith("}"):
                    body = body[:-1].rstrip()
                    if inits:
                        anchor = re.search(r"\n    private static synchronized void ensureInitLocked"
                                           r"\(\) \{", body)
                        if anchor:
                            end = balance_at(body, body.index("{", anchor.start()))
                            if end is not None:
                                body = (body[:end]
                                        + "".join("\n        " + st.strip() for st in inits)
                                        + "\n    " + body[end:])
                    merged = body + "\n\n" + "\n\n".join(pieces) + "\n}\n"
                reason = compile_verify(getattr(args, "repo", "."),
                                        os.path.join("src", "nsui", cls + ".java"), merged)
            if reason is None:
                text = merged
                kept_names = [unit_name(u) for u in pieces if unit_name(u)]
                lines.append("    PRESERVED %d hand-written member(s) and %d field(s), verified by "
                             "compiling: %s" % (len(kept_names), len(fields),
                                                ", ".join(kept_names[:8])
                                                + ("…" if len(kept_names) > 8 else "")))
            else:
                lines.append("    REFUSED-MERGE %d hand-written member(s) survive only by hand [%s]: "
                             "%s" % (len(still), reason,
                                     ", ".join(still[:6]) + ("…" if len(still) > 6 else "")))
        rel = os.path.join("src", "nsui", cls + ".java")
        files.append((rel, text))
        lines.append("class %s (%s, %s): %d generated, %d skipped, extends %s"
                     % (cls, surface.framework, rel_header, len(used), len(skipped), superclass))
        # Statements no parser branch claimed. Extern constants and enum bodies are expected; a
        # method or property shape here means a declaration was dropped, which is how
        # NSDatePicker.datePickerStyle went missing while the run still said "0 skipped".
        lost = [u for iface, _fw in surface.parts for u in getattr(iface, "unparsed", [])
                if "@property" in u or re.search(r"[+-]\s*\(", u)]
        if lost:
            lines.append("    UNPARSED %d declaration-shaped statement(s), e.g. %s"
                         % (len(lost), lost[0][:90]))
        lines.append("    surface: %d header bodies merged (%s)"
                     % (len(surface.parts),
                        ", ".join(sorted(set(fw for _iface, fw in surface.parts)))))
        for p in used:
            if getattr(p, "renamed_from", None):
                lines.append("    RENAMED %s -> %s   [both sides of the selector are declared]"
                             % (p.renamed_from, p.java_name))
        for p in skipped:
            lines.append("    SKIP %s%s  [%s]" % ("" if not p.is_class else "+",
                                                  p.decl.selector, p.reason))
            if p.reason.startswith("new Sig shape "):
                vocab_needed.append((p.shape[0], tuple(p.shape[1]), cls, p.decl.selector))
            if p.reason.startswith("new Sig shape"):
                new_shape_counter[p.reason] = new_shape_counter.get(p.reason, 0) + 1
    lines.append("")
    if new_shape_counter:
        lines.append("new Sig shapes required (%d distinct):" % len(new_shape_counter))
        for k in sorted(new_shape_counter):
            lines.append("    %s" % k)
    else:
        lines.append("new Sig shapes required: none")
    return files, lines, vocab_needed


def main(argv=None):
    ap = argparse.ArgumentParser(description="nsui code generator (stdlib only)")
    ap.add_argument("--repo", default=".", help="target repo root (never written without --apply)")
    ap.add_argument("--class", dest="classes", action="append", default=[],
                    help="ObjC class to generate (repeatable)")
    ap.add_argument("--framework", dest="frameworks", action="append", default=[],
                    help="framework to search for headers (repeatable)")
    ap.add_argument("--allow-drop", action="store_true",
                    help="with --apply: replace a hand-written wrapper even when the generated text "
                         "drops public members it declares (the default refuses and names them)")
    ap.add_argument("--apply", action="store_true",
                    help="write changed files into --repo (default: patch only)")
    ap.add_argument("--shipped-baseline", metavar="PATH",
                    help="measured shipped-wrapper verdicts (default codegen/shipped-baseline.json "
                         "next to gen.py); a case with no verdict is guarded")
    ap.add_argument("--guard-evidence", metavar="PATH",
                    help="measured bad-argument evidence (default codegen/guard-evidence.json)")
    ap.add_argument("--vocab-patch", metavar="PATH",
                    help="write a reviewable diff adding the Sig shapes this run needed but "
                         "the target vocabulary lacks")
    ap.add_argument("--check", action="store_true",
                    help="print the diff and exit 1 on drift; write nothing")
    ap.add_argument("--skip-deprecated", action="store_true")
    ap.add_argument("--patch-out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "proposed.patch"))
    ap.add_argument("--summary-out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "summary.txt"))
    ap.add_argument("--scratch", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), ".patchscratch"))
    ap.add_argument("--limit", type=int, default=25,
                    help="with --missing: how many classes to print (0 for all)")
    ap.add_argument("--json", metavar="PATH",
                    help="with --missing: write the list as JSON")
    ap.add_argument("--missing", action="store_true",
                    help="list the SDK classes the target tree does not wrap at all, with their "
                         "declaration counts; --limit 0 shows every one")
    ap.add_argument("--survey", nargs="*", default=None,
                    help="survey the named frameworks (default AppKit QuartzCore)")
    args = ap.parse_args(argv)
    if not args.frameworks:
        args.frameworks = ["AppKit", "Foundation", "QuartzCore"]
    if args.missing:
        return report_missing(args)
    if args.survey is not None:
        return survey(args.survey or ["AppKit", "QuartzCore"], args)

    sdk = find_sdk()
    repo = os.path.abspath(args.repo)
    vocab = load_vocabulary(os.path.join(repo, "src", "nsui", "objc", "Sig.java"))
    wrappers = load_wrappers(os.path.join(repo, "src", "nsui"))
    fws = list(dict.fromkeys(args.frameworks + ["AppKit", "Foundation", "QuartzCore"]))
    rt = objcabi.ObjCRuntime(fws)
    files, summary_lines, vocab_needed = gen_classes(args, sdk, vocab, wrappers, rt)
    if vocab_needed:
        distinct = len({(r, tuple(a)) for r, a, _c, _s in vocab_needed})
        print("NOTE %d method(s) need %d Sig shape(s) the target vocabulary lacks"
              % (len(vocab_needed), distinct))
        if args.vocab_patch:
            diff, rel = vocab_patch(repo, vocab_needed)
            if diff:
                with open(args.vocab_patch, "w", encoding="utf-8") as fh:
                    fh.write(diff)
                print("vocabulary patch: %s (%d shapes in %s)"
                      % (args.vocab_patch, distinct, rel))
            else:
                print("vocabulary patch: could not read %s" % rel)
    if not files:
        # Every requested class was skipped (no @interface, or unknown): reporting success here
        # would hide that nothing was generated at all.
        sys.stdout.write("\n".join(summary_lines) + "\n")
        print("nothing rendered for the requested classes (see the SKIP lines above)")
        return 1
    patch, pending = make_patch(repo, files, args.scratch)
    summary = "\n".join(summary_lines) + "\n"
    if args.check:
        sys.stdout.write(summary)
        sys.stdout.write(patch if patch else "(no drift: generated output already matches the tree)\n")
        return 1 if patch else 0
    with open(args.patch_out, "w", encoding="utf-8") as fh:
        fh.write(patch)
    with open(args.summary_out, "w", encoding="utf-8") as fh:
        fh.write(summary)
    print(summary)
    for rel, _t in files:
        status = "modified/new" if any(r == rel for r, _b, _n in pending) else "unchanged"
        print("%-8s %s" % (status, rel))
    if pending:
        print("patch: %s (%d bytes)" % (args.patch_out, len(patch)))
    else:
        print("no diff")
    if args.apply:
        written, _unchanged, refused = apply_plan(repo, pending, allow_drop=args.allow_drop)
        print("applied to %s: %s" % (repo, ", ".join(written) if written else "(nothing to write)"))
        for rel, lost in refused:
            if len(lost) == 1 and lost[0].startswith("the tree declares"):
                print("REFUSED %s: %s. Regenerating it needs --allow-drop." % (rel, lost[0]))
            else:
                print("REFUSED %s: it would drop %d public member(s) the tree declares (%s). "
                      "Replacing a hand-written wrapper needs --allow-drop, and merging them by hand "
                      "is safer." % (rel, len(lost), ", ".join(lost[:8])
                                     + ("…" if len(lost) > 8 else "")))
    return 0


if __name__ == "__main__":
    sys.exit(main())

