def find_sdk():
    try:
        p = subprocess.run(["xcrun", "--show-sdk-path"], capture_output=True, text=True)
        p = (p.stdout or "").strip()
        if p and os.path.isdir(p):
            return p
    except Exception:
        pass
    for cand in ("/Library/Developer/CommandLineTools/SDKs/MacOSX.sdk",):
        if os.path.isdir(cand):
            return cand
    raise SystemExit("no macOS SDK found (xcrun --show-sdk-path failed)")


def framework_headers_dir(sdk, fw):
    return os.path.join(sdk, "System", "Library", "Frameworks", fw + ".framework", "Headers")


_FRAMEWORK_CACHE = {}


def framework_interfaces(sdk, framework):
    """Every @interface/@protocol in one framework's public headers, parsed once.

    Categories are included: a category is part of the surface of the class it extends.
    """
    key = (sdk, framework)
    cached = _FRAMEWORK_CACHE.get(key)
    if cached is None:
        cached = hdrs.parse_framework(sdk, framework, include_categories=True)
        _FRAMEWORK_CACHE[key] = cached
    return cached


class Surface:
    """The merged declaration surface of one class (R3a).

    One class is normally declared in several bodies: its own `@interface` plus one category per
    feature area (`NSExtendedArray`, `NSArrayCreation`, ...). Reading only the first body is why
    NSArray generated 3 of its 53 shipped methods. A Surface is the union of all of them:

        decls      the union, deduplicated by (selector, is_class); the class's own body comes
                   first so it wins a conflict, then the other bodies pinned by
                   (framework, file path, line number).
        parts      (Interface, framework) for every contributing body, in that order.
        own        (Interface, framework) of the class's own body, or None if it has none.
        file       the header the class's own body was read from (the banner path).
        superclass the class's own superclass, when its own body declares one.
        protocols  the protocols the class's own body adopts; R3b merges their declarations.
    """

    __slots__ = ("decls", "parts", "own", "superclass", "protocols", "file", "framework")

    def __init__(self, own, parts, decls):
        self.own = own
        self.parts = parts
        self.decls = decls
        self.superclass = own[0].superclass if own else None
        self.protocols = own[0].protocols if own else []
        self.file = own[0].file if own else parts[0][0].file
        self.framework = own[1] if own else parts[0][1]


def collect_surface(cls, frameworks, sdk=None):
    """Every declaration that belongs to `cls`, merged from every body that declares it.

    Returns a Surface (or None when no framework declares the class) built from all
    `@interface <cls> ...` bodies plus every `@interface <cls> (Category)`. The bodies are
    ordered own-body-first and then by (framework, file path, line number) — pinned, because
    the walk that found them yields directory order, which is not stable, and the merge must
    not depend on it. A (selector, is_class) declared by more than one body is kept once, from
    the first body in that order, so the class's own declaration wins a conflict.

    Only bodies *named* `cls` qualify: `@interface NSView (NSGestureRecognizer)` declares NSView
    methods and is not part of NSGestureRecognizer's surface.
    """
    if sdk is None:
        sdk = find_sdk()
    found = []
    for index, fw in enumerate(frameworks):
        for iface in framework_interfaces(sdk, fw):
            if iface.kind == "interface" and iface.name == cls:
                found.append((iface.category is not None, index, fw, iface))
    if not found:
        return None
    found.sort(key=lambda t: (t[0], t[1], t[3].file, t[3].line))
    own = None
    parts = []
    decls = []
    seen = set()
    for is_category, _index, fw, iface in found:
        if own is None and not is_category:
            own = (iface, fw)
        parts.append((iface, fw))
        for decl in iface.decls:
            key = (decl.selector, bool(decl.is_class))
            if key in seen:
                continue
            seen.add(key)
            decls.append(decl)
    return Surface(own, parts, decls)


def find_header(sdk, cls, frameworks):
    """The one body the old first-match walk returned: the class's own @interface, else the
    first body that declares it.

    Kept for the audit probes that compare against the pre-R3a behaviour
    (codegen/work/plan_probe.py); gen_classes reads the whole surface via collect_surface().
    """
    surface = collect_surface(cls, frameworks, sdk)
    if surface is None:
        return None, None, None
    iface, fw = surface.own or surface.parts[0]
    return iface.file, fw, iface


def _out_param(p):
    if p.is_out:
        return True
    return bool(re.match(r"^\s*(id|NSError|NSRect|CGRect|NSPoint|CGPoint|NSSize|CGSize|"
                         r"NSRange|CGFloat|NSInteger|NSUInteger|BOOL|double|float|int|long|"
                         r"NSRectEdge)\s*\*+\s*$", p.type_raw or ""))


def survey(frameworks, args):
    sdk = find_sdk()
    rt = objcabi.ObjCRuntime(list(frameworks))
    repo = os.path.abspath(args.repo)
    vocab = load_vocabulary(os.path.join(repo, "src", "nsui", "objc", "Sig.java"))
    c = {}
    examples = {}
    shapes = {}
    newshapes = {}
    structs = {}

    def bump(k, n=1):
        c[k] = c.get(k, 0) + n

    def ex(reason, s):
        L = examples.setdefault(reason, [])
        if len(L) < 8:
            L.append(s)

    seen = set()
    for fw in frameworks:
        for iface in hdrs.parse_framework(sdk, fw, include_categories=True):
            bucket = ("protocol" if iface.kind == "protocol"
                      else ("category" if iface.category else "class"))
            bump(bucket + "_bodies")
            bump(bucket + "_bodies:" + fw)
            for d in iface.decls:
                bump("decls")
                bump(bucket + "_decls")
                if d.kind == "method":
                    bump("methods")
                if d.property:
                    bump("property_accessors")
                if d.is_class:
                    bump("class_methods")
                if d.multiline:
                    bump("multiline_decls")
                if any(p.is_block for p in d.params):
                    bump("decls_with_block_param")
                if any(_out_param(p) for p in d.params):
                    bump("decls_with_out_param")
                if any(p.is_generic for p in d.params) or "<" in d.ret_raw:
                    bump("decls_with_generics")
                if "..." in d.raw:
                    bump("decls_variadic")
                if d.deprecated:
                    bump("decls_deprecated")
                if d.unavailable:
                    bump("decls_unavailable")
                key = (d.owner, d.selector, d.is_class)
                if key in seen:
                    bump("duplicate_decls")
                    continue
                seen.add(key)
                enc, kind = rt.encoding(d.owner, d.selector)
                if enc is None:
                    bump("unresolved")
                    bump("unresolved_" + kind)
                    bump(bucket + "_unresolved_" + kind)
                    ex(kind, "%s %s%s" % (d.owner, "-" if not d.is_class else "+", d.selector))
                    continue
                bump("resolved")
                if (d.is_class and kind != "class") or (not d.is_class and kind != "inst"):
                    bump("kind_mismatch")
                    bump("kind_mismatch_" + bucket)
                shape = objcabi.shape_of(enc)
                if shape is None:
                    bump("unparseable_encoding")
                    continue
                shapes[shape] = shapes.get(shape, 0) + 1
                if shape in vocab:
                    bump(bucket + "_in_vocab")
                else:
                    bump(bucket + "_new_shape")
                    newshapes[shape] = newshapes.get(shape, 0) + 1
                for tok in objcabi.parse_types(enc):
                    if tok.startswith("{"):
                        nm = objcabi.struct_name(tok)
                        sz = objcabi.struct_bytes(tok)
                        structs[(nm, sz)] = structs.get((nm, sz), 0) + 1

    L = []
    L.append("CodeGen %s survey - %s" % (VERSION, ", ".join(frameworks)))
    L.append("SDK: %s" % sdk)
    L.append("")
    L.append("-- declarations parsed --")
    for k in ("class_bodies", "category_bodies", "protocol_bodies", "decls", "methods",
              "property_accessors", "class_methods", "duplicate_decls"):
        L.append("  %-28s %d" % (k, c.get(k, 0)))
    L.append("")
    L.append("-- features (of %d distinct decls) --" % len(seen))
    for k in ("multiline_decls", "decls_with_block_param", "decls_with_out_param",
              "decls_with_generics", "decls_variadic", "decls_deprecated",
              "decls_unavailable"):
        L.append("  %-28s %d" % (k, c.get(k, 0)))
    L.append("")
    L.append("-- runtime resolution --")
    L.append("  %-28s %d" % ("resolved", c.get("resolved", 0)))
    L.append("  %-28s %d" % ("unresolved", c.get("unresolved", 0)))
    for k in sorted(c):
        if k.startswith("unresolved_"):
            L.append("  %-28s %d" % (k, c[k]))
    L.append("  %-28s %d" % ("kind_mismatch", c.get("kind_mismatch", 0)))
    L.append("")
    L.append("-- shape split (distinct selectors by declaration site) --")
    for b in ("class", "category", "protocol"):
        iv, nv = c.get(b + "_in_vocab", 0), c.get(b + "_new_shape", 0)
        un = sum(v for k, v in c.items() if k.startswith(b + "_unresolved_"))
        L.append("  %-9s in Sig.VOCABULARY: %-6d needs new shape: %-6d  unresolved: %-6d"
                 % (b, iv, nv, un))
    L.append("  distinct shapes seen: %d   in vocabulary: %d   new: %d"
             % (len(shapes), len([s for s in shapes if s in vocab]),
                len([s for s in shapes if s not in vocab])))
    L.append("")
    L.append("-- top new Sig shapes (class/category only) --")
    cls_new = {}
    for s, n in newshapes.items():
        cls_new[s] = n
    for s, n in sorted(cls_new.items(), key=lambda kv: -kv[1])[:25]:
        L.append("  %-6d of(Ret.%s%s)" % (n, s[0], "".join(", Arg.%s" % a for a in s[1])))
    L.append("")
    L.append("-- struct tokens by size --")
    big = [(k, v) for k, v in structs.items() if (k[1] or 0) > 16]
    small = [(k, v) for k, v in structs.items() if (k[1] or 0) <= 16]
    L.append("  distinct <=16B: %d   distinct >16B: %d" % (len(small), len(big)))
    for (nm, sz), n in sorted(big, key=lambda kv: -kv[1])[:20]:
        L.append("  %-34s %4s bytes  x%d" % (nm, sz, n))
    L.append("")
    L.append("-- failure examples --")
    for reason in sorted(examples):
        for s in examples[reason]:
            L.append("  %-22s %s" % (reason, s))
    text = "\n".join(L) + "\n"
    report_txt = os.path.join(os.path.dirname(os.path.abspath(__file__)), "survey.txt")
    report_json = os.path.join(os.path.dirname(os.path.abspath(__file__)), "survey.json")
    with open(report_txt, "w", encoding="utf-8") as fh:
        fh.write(text)
    with open(report_json, "w", encoding="utf-8") as fh:
        json.dump({"counters": c, "examples": examples,
                   "new_shapes": [{"ret": s[0], "args": list(s[1]), "count": n}
                                  for s, n in sorted(newshapes.items(), key=lambda kv: -kv[1])],
                   "structs_over_16": [{"name": k[0], "bytes": k[1], "count": v}
                                       for k, v in sorted(structs.items(), key=lambda kv: -(kv[0][1] or 0))]},
                  fh, indent=1, sort_keys=True)
    print(text)
    return 0


