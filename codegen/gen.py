#!/usr/bin/env python3
"""gen.py - pure-stdlib code generator for nsui-style Objective-C wrappers.

Pipeline
    SDK headers (hdrs.py)  ->  runtime type encoding (objcabi.py, ctypes)
                           ->  Sig shape  ->  Java source (house style)
                           ->  git diff --no-index  ->  proposed.patch

Modes
    gen.py --class NSSharingService --repo <tree> [--apply]   render + patch
    gen.py --check --class X --repo <tree>                    report diff, write nothing
    gen.py --survey AppKit QuartzCore                         feasibility numbers

Constraints: Python 3 stdlib only; the live tree is never written unless --apply
is given AND the rendered body actually differs.
"""
from __future__ import annotations

