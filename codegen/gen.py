def _git_diff_trees(pending, scratch):
    if os.path.isdir(scratch):
        shutil.rmtree(scratch)
    os.makedirs(scratch)
    a = os.path.join(scratch, "a")
    b = os.path.join(scratch, "b")
    # Both roots must exist even when one side is empty: a new-file-only patch
    # has no "a" entries at all, and git refuses a missing path.
    os.makedirs(a, exist_ok=True)
    os.makedirs(b, exist_ok=True)
    for rel, base_text, new_text in pending:
        pa = os.path.join(a, rel)
        pb = os.path.join(b, rel)
        if base_text is not None:
            os.makedirs(os.path.dirname(pa), exist_ok=True)
            with open(pa, "w", encoding="utf-8") as fh:
                fh.write(base_text)
        os.makedirs(os.path.dirname(pb), exist_ok=True)
        with open(pb, "w", encoding="utf-8") as fh:
            fh.write(new_text)
    proc = subprocess.run(["git", "diff", "--no-index", "--no-color",
                           "--src-prefix=", "--dst-prefix=", "a", "b"],
                          cwd=scratch, capture_output=True, text=True)
    return proc.stdout


def make_patch(repo, plan, scratch):
    pending = []
    for rel, new_text in plan:
        path = os.path.join(repo, rel)
        base = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                base = fh.read()
        if base == new_text:
            continue
        pending.append((rel, base, new_text))
    text = _git_diff_trees(pending, scratch) if pending else ""
    return text, pending


def apply_plan(repo, pending):
    written = []
    unchanged = []
    for rel, _base, new_text in pending:
        path = os.path.join(repo, rel)
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                if fh.read() == new_text:
                    unchanged.append(rel)
                    continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new_text)
        written.append(rel)
    return written, unchanged


