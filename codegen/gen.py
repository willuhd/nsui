SCALAR_TYPE_NAMES = {"void", "BOOL", "bool", "char", "short", "int", "long", "float", "double",
                     "NSInteger", "NSUInteger", "CGFloat", "NSTimeInterval", "CFTimeInterval",
                     "unsigned", "signed", "size_t", "int32_t", "int64_t", "uint32_t", "uint64_t"}


POINTER_QUALIFIERS = re.compile(r"^[rnNoOV]+")


def token_is_pointer(tok):
    """True when an encoding token is a pointer (`^`, `r^`, `^{_NSRange=QQ}`, `^^`)."""
    return bool(tok) and POINTER_QUALIFIERS.sub("", tok).startswith("^")


def is_out_parameter(par, wrappers):
    """Conservative header-only view of the same question, for the survey's statistics.

    Emission uses the encoding token (see build_plan); this exists for callers that only have the
    declaration. An uppercase base name is assumed to be an ObjC class, so an unwrapped `NSURL *`
    is not miscounted as an out slot.
    """
    if par.is_out:
        return True
    t = re.sub(r"\b(nullable|nonnull|_Nullable|_Nonnull|__kindof|const|volatile|inout|out)\b",
               " ", par.type_raw or "")
    t = re.sub(r"<[^<>]*>", " ", t)
    depth = t.count("*") + t.count("^")
    if not depth:
        return False
    if depth > 1:
        return True                  # pointer to a pointer
    base = base_type(t)
    return bool(base) and not base[0].isupper()


def is_construction_selector(sel):
    """True for the alloc/new families: they hand back an uninitialised object.

    `allocWithZone:` belongs to `alloc`, which the flat blacklist missed; this is the Objective-C
    family rule (the name itself, or the name followed by a non-lowercase character), not a
    per-class exception.
    """
    first = sel.split(":")[0]
    for fam in ("alloc", "new"):
        if first == fam or (first.startswith(fam) and not first[len(fam)].islower()):
            return True
    return False


def is_init_family(sel, ret_raw):
    """True for a real initializer: `init`, or `init` followed by a non-lowercase character.

    A plain prefix test also swallowed `-initialVelocity` (a CGFloat getter whose setter was
    generated, so the class lost half a property) and `+initialize`.
    """
    if not sel.startswith("init"):
        return False
    if len(sel) > 4 and sel[4].islower():
        return False
    base = base_type(ret_raw)
    if base in ("", "id", "instancetype"):
        return True
    return base not in SCALAR_TYPE_NAMES          # self-class returns stay initializers


DEFAULT_GUARD_EVIDENCE = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                       "guard-evidence.json")


def load_guard_evidence(path=None):
    """Measured bad-argument evidence: {(class, selector): [entry, ...]}.

    Guards exist because a nil argument, an out-of-range index or NaN geometry makes AppKit abort
    the process, and that is not readable from a header. codegen/probe.py measures it in a child
    process and codegen/guard-evidence.json records it, so the generator emits what was measured
    instead of growing a table of per-class exceptions.
    """
    path = path or DEFAULT_GUARD_EVIDENCE
    try:
        with open(path, encoding="utf-8") as fh:
            data = json.load(fh)
    except (OSError, ValueError):
        return {}, path
    out = {}
    for case in data.get("cases", []):
        out.setdefault((case.get("class"), case.get("selector")), []).append(case)
    return out, path


def load_shipped_baseline(path=None):
    """{probe id: verdict measured against the SHIPPED wrappers}, or {} when not measured.

    The emission rule is "guard unless the shipped wrapper was measured tolerating this argument":
    an abort or a Java exception in the shipped wrapper both mean the generated wrapper should
    reject too, while a tolerated call means a guard there would be stricter than the shipped API.
    A case with no measured verdict at all is guarded — absence of evidence is not tolerance — and
    the run reports how many such cases it guarded.
    """
    path = path or os.path.join(os.path.dirname(os.path.abspath(__file__)), "shipped-baseline.json")
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh).get("verdicts", {})
    except (OSError, ValueError):
        return {}


def bound_is_usable(bound, plans, repo):
    """Whether a bound copied from the corpus still compiles against the generated class.

    The corpus may call a convenience the generator does not emit: the shipped
    NSLayoutManager.textContainers() returns a hand-written java.util.List, so its guard says
    `.size()`, while the generated method returns NSArray, which has count(). Emitting the bound
    verbatim produced a file that did not compile.
    """
    names = {q.java_name: q for q in plans if not q.skip}
    m = re.match(r"^([A-Za-z_]\w*)\(\)$", bound)
    if m:
        return m.group(1) in names
    m = re.match(r"^([A-Za-z_]\w*)\(\)\.([A-Za-z_]\w*)\(\)$", bound)
    if not m:
        return False
    first, second = m.groups()
    q = names.get(first)
    if q is None:
        return False
    path = os.path.join(repo, "src", "nsui", q.ret_java + ".java")
    if not os.path.exists(path):
        return False
    with open(path, encoding="utf-8", errors="replace") as fh:
        return re.search(r"\b%s\s*\(" % re.escape(second), fh.read()) is not None


def guard_template(case):
    """The guard statement for a measured case, derived from what was measured.

    The evidence stores the statement for the cases it emitted from, and for a control — a call the
    generated wrapper tolerated — the kind is enough: a nil argument takes nonNull, NaN geometry
    notNaN, and an index takes the bound the shipped wrapper uses.
    """
    sel, badness = case.get("selector"), case.get("badness")
    if badness == "nil":
        return ['Bounds.nonNull({p}, "%s");' % sel]
    if badness == "nan":
        return ['Bounds.notNaN({p}, "%s");' % sel]
    if badness == "index" and case.get("bound"):
        return ['Bounds.index({p}, %s, "%s");' % (case["bound"], sel)]
    return []


def unique_local(base, used):
    """A local variable name that cannot collide with anything already in scope.

    Header parameter names are arbitrary (`convertTime:fromLayer:` names its parameter `t`), so a
    fixed catch or temp variable can shadow one and produce "variable t is already defined".
    """
    name = base
    while name in used:
        name += "_"
    return name


def render_method(p, class_name):
    d, shape = p.decl, p.shape
    ret, args = shape
    recv = 'ObjC.cls("%s")' % class_name if p.is_class else "peer"
    params = ", ".join("%s %s" % (jt, nm) for _k, jt, nm in p.params)
    args_java = []
    for (k, _jt, nm) in p.params:
        if k == "id":
            args_java.append(nm)
        elif k == "string":
            # The explicit cast is load-bearing (same as the hand-written wrappers):
            # without it javac types the conditional as Object and invokeExact rejects it.
            args_java.append("(MemorySegment) (%s == null ? MemorySegment.NULL : ObjC.nsstring(%s))" % (nm, nm))
        elif k.startswith("typed:"):
            args_java.append("(MemorySegment) (%s == null ? MemorySegment.NULL : %s.peer())" % (nm, nm))
        elif k in ("long", "boolean", "double", "float", "byte", "int", "short"):
            args_java.append(nm)
        elif k == "uint32":
            args_java.append("(int) " + nm)
        else:
            args_java.append("%s.toSegment()" % nm)
    call_args = ", ".join([recv, "Sels." + p.field] + args_java)
    alloc = None
    if ret in STRUCT_JAVA:
        alloc = "CATransform3D.slot()" if ret == "TRANSFORM3D" else "ObjC.structSlot()"
    static = "static " if p.is_class else ""
    lines = []
    dep = " (deprecated)" if d.deprecated else ""
    lines.append("    /// %s%s - generated from %s." % (d.selector, dep, d.raw[:90]))
    lines.append("    public %s%s %s(%s) {" % (static, p.ret_java, p.java_name, params))
    lines.append("        ensureInit();")
    for setup in getattr(p, "guard_setup", []) or []:
        lines.append("        " + setup)
    for guard in getattr(p, "guards", []) or []:
        for gl in guard.split("\n"):       # an evidence statement may be a small block
            lines.append("        " + gl)
    lines.append("        try {")
    if ret == "VOID":
        lines.append("            H.%s().invokeExact(%s);" % (p.handle, call_args))
    elif ret == "INT32" and p.ret_kind == "uint32":
        # uint32_t return: read exactly 32 bits, then zero-extend into the long surface
        # (the house form in MTLStencilDescriptor.readMask).
        lines.append("            return ((int) H.%s().invokeExact(%s)) & 0xFFFFFFFFL;"
                     % (p.handle, call_args))
    elif ret == "SHORT" and p.ret_kind == "uint16":
        # unsigned short return: 16 bits, zero-extended into the long surface
        lines.append("            return ((int) H.%s().invokeExact(%s)) & 0xFFFFL;"
                     % (p.handle, call_args))
    elif ret in SCALAR_JAVA:
        # The cast is the exact-width read: INT32 is a 4-byte JAVA_INT handle, SHORT a
        # 2-byte JAVA_SHORT one, INT the 64-bit C-long class.  Widening an int return to
        # long without the cast would read 64 bits of a 32-bit write.
        cast = {"INT": "long", "BOOL": "boolean", "DOUBLE": "double", "FLOAT": "float",
                "BYTE": "byte", "INT32": "int", "SHORT": "short"}[ret]
        lines.append("            return (%s) H.%s().invokeExact(%s);" % (cast, p.handle, call_args))
    elif ret in STRUCT_JAVA:
        lines.append("            MemorySegment seg = (MemorySegment) H.%s().invokeExact(%s, %s);"
                     % (p.handle, alloc, call_args))
        lines.append("            return %s.fromSegment(seg);" % STRUCT_JAVA[ret])
    else:  # ID
        lines.append("            MemorySegment r = (MemorySegment) H.%s().invokeExact(%s);"
                     % (p.handle, call_args))
        if p.ret_kind == "string":
            lines.append("            return ObjC.toString(r);")
        elif p.ret_kind == "typed":
            lines.append("            return %s.wrap(r);" % p.ret_java)
        else:
            lines.append("            return r;")
    exc = unique_local("t", {nm for _k, _jt, nm in p.params})
    lines.append("        } catch (Throwable %s) { throw new RuntimeException(\"%s failed\", %s); }"
                 % (exc, d.selector, exc))
    lines.append("    }")
    return "\n".join(lines)


def render_class(class_name, superclass, header_rel, plans, surface, framework="AppKit",
                 protected_init=False):
    used = [p for p in plans if not p.skip]
    handles = OrderedDict()
    for p in sorted(used, key=lambda q: (q.shape[0], q.shape[1])):
        handles[p.handle] = p.shape
    fields = OrderedDict()
    for p in sorted(used, key=lambda q: q.field):
        fields[p.field] = p.decl.selector

    L = []
    L.append(MARKER)
    L.append("package nsui;")
    L.append("")
    L.append("import java.lang.foreign.MemorySegment;")
    if handles:
        L.append("import java.lang.invoke.MethodHandle;")
    L.append("")
    L.append("import nsui.objc.ObjC;")
    L.append("import nsui.objc.Sig;")
    L.append("import static nsui.objc.Sig.Arg;")
    L.append("import static nsui.objc.Sig.Ret;")
    L.append("")
    L.append("/// %s - generated wrapper (CodeGen %s) from %s." % (class_name, VERSION, header_rel))
    L.append("///")
    if surface is not None and len(surface.parts) > 1:
        L.append("/// Merged surface: the class's own @interface wins a conflicting selector; the")
        L.append("/// other %d bodies are categories declared on it (%s)."
                 % (len(surface.parts) - 1,
                    ", ".join(sorted(set(fw for _iface, fw in surface.parts)))))
        L.append("///")
    L.append("/// %d methods generated from the ObjC runtime type encoding; every shape is in" % len(used))
    L.append("/// Sig.VOCABULARY and is checked by tests/SignatureConformanceTest. Do not edit")
    L.append("/// by hand: rerun codegen/gen.py --apply and review the emitted patch.")
    skipped = [p for p in plans if p.skip]
    if skipped:
        L.append("///")
        L.append("/// Omitted (%d): %s" % (len(skipped),
                 ", ".join(sorted(set(p.reason for p in skipped)))))
    L.append("public class %s extends %s {" % (class_name, superclass))
    L.append("")
    # selectors
    L.append("    /// Cached selectors, populated once from ensureInitLocked().")
    L.append("    private static final class Sels {")
    for f in fields:
        L.append("        static MemorySegment %s;" % f)
    L.append("        static void populate() {")
    for f, sel in fields.items():
        L.append("            %s = ObjC.sel(\"%s\");" % (f, sel))
    L.append("        }")
    L.append("    }")
    L.append("")
    # handles -- always emitted: ensureInit() reads H unconditionally, so a class whose
    # declarations were all skipped still needs an (empty) Handles record or it will not compile
    comps = ", ".join("MethodHandle %s" % h for h in handles)
    L.append("    private record Handles(%s) {}" % comps)
    L.append("    private static volatile Handles H;")
    L.append("")
    L.append("    protected %s(MemorySegment peer) {" % class_name)
    L.append("        super(peer);")
    L.append("        ensureInit();")
    L.append("    }")
    L.append("")
    L.append("    /// Wrap an id as %s (null for nil)." % class_name)
    L.append("    public static %s wrap(MemorySegment peer) {" % class_name)
    L.append("        return (peer == null || peer.address() == 0) ? null : new %s(peer);" % class_name)
    L.append("    }")
    L.append("")
    L.append("    %s static void ensureInit() {" % ("protected" if protected_init else "private"))
    L.append("        if (H != null) return;")
    L.append("        ensureInitLocked();")
    L.append("    }")
    L.append("")
    L.append("    %s static synchronized void ensureInitLocked() {"
             % ("protected" if protected_init else "private"))
    L.append("        if (H != null) return;")
    fw = framework or "AppKit"
    L.append("        try { ObjC.ensureFramework(\"%s\"); } catch (Throwable ignored) {}" % fw)
    if handles:
        L.append("        Handles h = new Handles(")
        for i, h in enumerate(handles):
            sh = handles[h]
            sig = "Sig.of(Ret.%s%s)" % (sh[0], "".join(", Arg.%s" % a for a in sh[1]))
            comma = "," if i < len(handles) - 1 else ");"
            L.append("                ObjC.handle(%s)%s" % (sig, comma))
    else:
        L.append("        Handles h = new Handles();")
    L.append("        Sels.populate();")
    L.append("        H = h;")
    L.append("    }")
    L.append("")
    for p in sorted(used, key=lambda q: (q.is_class, q.java_name)):
        L.append(render_method(p, class_name))
        L.append("")
    L.append("}")
    return "\n".join(L) + "\n"


def vocab_patch(repo, needed):
    """A unified diff adding the missing Sig shapes to the target tree's Sig.java.

    The generator never writes into src/, so the shapes its runtime ABI needs but the target
    vocabulary lacks are offered as a reviewable patch, each entry commented with an example
    method that needs it. Applying it (and re-running the gate) is what makes those methods
    generatable.
    """
    rel = os.path.join("src", "nsui", "objc", "Sig.java")
    path = os.path.join(repo, rel)
    try:
        with open(path, encoding="utf-8") as fh:
            old = fh.readlines()
    except OSError:
        return None, rel
    start = next((i for i, l in enumerate(old) if "VOCABULARY = List.of(" in l), None)
    if start is None:
        return None, rel
    end = next((i for i in range(start, len(old)) if re.match(r"\s*\);\s*$", old[i])), None)
    if end is None:
        return None, rel
    original = list(old)          # the diff's "before" side must stay untouched: mutating it in
    last = end - 1                # place made the added comma show up as context and the patch
    while last > start and (not old[last].strip() or old[last].lstrip().startswith("//")):
        last -= 1
    # The comma has to go before any trailing `// comment`, or it lands inside the comment and
    # the List.of(...) loses that argument entirely.
    code, sep, comment = old[last].rstrip("\n").partition("//")
    if not code.rstrip().endswith(","):
        old[last] = code.rstrip() + "," + (("  " + sep + comment) if sep else "") + "\n"
    entries = []
    seen = set()
    for ret, args, cls, sel in sorted(needed):
        key = (ret, tuple(args))
        if key in seen:
            continue
        seen.add(key)
        sig = "of(Ret.%s%s)" % (ret, "".join(", Arg.%s" % a for a in args))
        pad = " " * max(1, 54 - len(sig))
        entries.append("        %s,%s// %s.%s\n" % (sig, pad, cls, sel))
    if entries:
        # Java rejects a trailing comma in a call, and the comma here sits before the trailing
        # comment, so it has to be dropped there rather than at end-of-line.
        code, sep, comment = entries[-1].rstrip("\n").partition("//")
        entries[-1] = code.rstrip().rstrip(",") + (("  " + sep + comment) if sep else "") + "\n"
    new = old[:end] + entries + old[end:]
    return "".join(difflib.unified_diff(original, new, "a/" + rel, "b/" + rel, n=3)), rel


