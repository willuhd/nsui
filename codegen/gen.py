def _git_diff_trees(pending, scratch):
    if os.path.isdir(scratch):
        shutil.rmtree(scratch)
    os.makedirs(scratch)
    a = os.path.join(scratch, "a")
    b = os.path.join(scratch, "b")
    # Both roots must exist even when one side is empty: a new-file-only patch
    # has no "a" entries at all, and git refuses a missing path.
    os.makedirs(a, exist_ok=True)
    os.makedirs(b, exist_ok=True)
    for rel, base_text, new_text in pending:
        pa = os.path.join(a, rel)
        pb = os.path.join(b, rel)
        if base_text is not None:
            os.makedirs(os.path.dirname(pa), exist_ok=True)
            with open(pa, "w", encoding="utf-8") as fh:
                fh.write(base_text)
        os.makedirs(os.path.dirname(pb), exist_ok=True)
        with open(pb, "w", encoding="utf-8") as fh:
            fh.write(new_text)
    proc = subprocess.run(["git", "diff", "--no-index", "--no-color",
                           "--src-prefix=", "--dst-prefix=", "a", "b"],
                          cwd=scratch, capture_output=True, text=True)
    return proc.stdout


def make_patch(repo, plan, scratch):
    pending = []
    for rel, new_text in plan:
        path = os.path.join(repo, rel)
        base = None
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                base = fh.read()
        if base == new_text:
            continue
        pending.append((rel, base, new_text))
    text = _git_diff_trees(pending, scratch) if pending else ""
    return text, pending


def apply_plan(repo, pending, allow_drop=False):
    """Write the generated files, refusing to delete a hand-written wrapper's public API.

    The generator reproduces what the SDK declares; the tree's own wrappers add typed conveniences
    and factories it cannot derive (NSTextField.create(NSRect frame), String stringValue()). Copying
    such a file over one of them silently removed that API and broke its callers, tests/ included.
    A merge was attempted and abandoned: deciding by identifier names both kept a member that needed
    a hand-written private handle and dropped the factory that only needed ObjC.newView, and a guess
    that emits a file which cannot compile is worse than not writing it. So the write is refused,
    the lost members are named, and --allow-drop says to replace anyway.
    """
    written, unchanged, refused = [], [], []
    for rel, _base, new_text in pending:
        path = os.path.join(repo, rel)
        existing = ""
        if os.path.exists(path):
            with open(path, encoding="utf-8", errors="replace") as fh:
                existing = fh.read()
            if existing == new_text:
                unchanged.append(rel)
                continue
        if existing and MARKER not in existing and not allow_drop:
            # The tree's projection decides the kind. NSUserInterfaceItemIdentification is a
            # hand-written interface; writing the generator's class over it broke every
            # `implements` in the corpus (NSToolbarItem among them).
            kind = re.search(r"^\s*(?:public\s+)?(interface|enum|record|class)\s+(\w+)", existing, re.M)
            if kind and kind.group(1) != "class":
                refused.append((rel, ["the tree declares it as %s %s and the generator emits a class"
                                      % (kind.group(1), kind.group(2))]))
                continue
            was = set(re.findall(r"public\s+(?:static\s+)?[\w.<>\[\]]+\s+(\w+)\s*\(", existing))
            now = set(re.findall(r"public\s+(?:static\s+)?[\w.<>\[\]]+\s+(\w+)\s*\(", new_text))
            lost = sorted(was - now)
            if lost:
                refused.append((rel, lost))
                continue
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(new_text)
        written.append(rel)
    return written, unchanged, refused


