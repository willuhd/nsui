#!/usr/bin/env python3
"""CodeGen sweep — point the generator at any commit and harden it against the result.

For a chosen point in history this finds the wrapper classes that exist TODAY but not at that
commit, generates them into a scratch extraction of the commit, compiles the result against that
tree's own sources, and (when the commit has one) runs its signature gate. Failures are grouped so
the generator can be fixed generally rather than per class.

Nothing in the live tree is written: the target is codegen/work/<sha>-sweep/, and `--inject-vocab`
copies today's Sig.java in so the vocabulary gap of an old tree does not hide emission defects.

  python3 codegen/sweep.py --commit 3640e2e8 --inject-vocab --gate Signature
  python3 codegen/sweep.py --commit 42dac7f --limit 40 --no-inject-vocab
  python3 codegen/sweep.py --commit 3640e2e8 --classes NSArray,NSOrderedSet
"""

import argparse
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import time
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import bench  # noqa: E402  (reuse the snapshot/gate plumbing)
import gen    # noqa: E402  (VERSION, vocabulary count)

GRAALVM = os.environ.get("GRAALVM", "/Library/Java/JavaVirtualMachines/graalvm-25.jdk/Contents/Home")
JAVAC = os.path.join(GRAALVM, "bin", "javac")
JAVA = os.path.join(GRAALVM, "bin", "java")
SVM_JAR = os.path.join(GRAALVM, "lib", "svm", "builder", "svm.jar")


def current_wrappers():
    """Classes in the current tree that expose the house `wrap(MemorySegment)` factory."""
    out = []
    src = os.path.join(REPO, "src", "nsui")
    for fn in sorted(os.listdir(src)):
        if not fn.endswith(".java"):
            continue
        text = open(os.path.join(src, fn), encoding="utf-8", errors="replace").read()
        name = fn[:-5]
        if re.search(r"static\s+%s\s+wrap\s*\(\s*MemorySegment" % re.escape(name), text):
            out.append(name)
    return out


def classes_missing_at(snap):
    missing = []
    for cls in current_wrappers():
        if not os.path.exists(os.path.join(snap, "src", "nsui", cls + ".java")):
            missing.append(cls)
    return missing


def snapshot_for(commit, inject_vocab):
    """A pristine sweep-private copy of `commit`, optionally carrying today's Sig.java.

    Always rebuilt: a previous sweep leaves generated files and an injected vocabulary behind, and
    a reused directory silently measures those instead of the generator (that mistake produced a
    phantom NSComboBox failure once).
    """
    dest = os.path.join(bench.WORK, "%s-sweep%s" % (commit[:12], "-vocab" if inject_vocab else ""))
    if os.path.exists(dest):
        shutil.rmtree(dest)
    shutil.copytree(bench.snapshot(commit), dest, symlinks=True)
    if inject_vocab:
        src = os.path.join(REPO, "src", "nsui", "objc", "Sig.java")
        dst_dir = os.path.join(dest, "src", "nsui", "objc")
        if os.path.isdir(dst_dir):
            shutil.copy2(src, os.path.join(dst_dir, "Sig.java"))
    return dest


def is_generated(path):
    """True when the file carries the generator's marker (so failures can be attributed)."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            return fh.readline().startswith("/// @generated by CodeGen")
    except OSError:
        return False


def generate(snap, classes, frameworks, batch=30):
    """Run the generator over the classes, in batches, collecting its summary lines."""
    lines = []
    rc_all = 0
    for i in range(0, len(classes), batch):
        chunk = classes[i:i + batch]
        cmd = [sys.executable, os.path.join(HERE, "gen.py"), "--repo", snap, "--apply",
               "--patch-out", os.path.join(bench.REPORTS, "sweep.patch"),
               "--summary-out", os.path.join(bench.REPORTS, "sweep-summary.txt"),
               "--scratch", os.path.join(bench.WORK, "sweep-scratch")]
        for c in chunk:
            cmd += ["--class", c]
        for f in frameworks:
            cmd += ["--framework", f]
        p = subprocess.run(cmd, cwd=REPO, capture_output=True, text=True)
        rc_all = rc_all or p.returncode
        lines.extend((p.stdout or "").splitlines())
    return rc_all, lines


def skip_histogram(summary_lines):
    hist = Counter()
    for ln in summary_lines:
        m = re.search(r"SKIP .*?\[(.*)\]$", ln.strip())
        if m:
            hist[re.sub(r"\d+", "N", m.group(1))] += 1
    return hist


def compile_snapshot(snap, include_gate):
    """javac the snapshot's src/nsui (+ its gate test when present). Returns (rc, errors, log)."""
    out = os.path.join(bench.WORK, "sweep-classes")
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out, exist_ok=True)
    sources = [os.path.join(snap, "src", "nsui", f)
               for f in sorted(os.listdir(os.path.join(snap, "src", "nsui"))) if f.endswith(".java")]
    sources += [os.path.join(snap, "src", "nsui", "objc", f)
                for f in sorted(os.listdir(os.path.join(snap, "src", "nsui", "objc")))
                if f.endswith(".java")]
    tests = []
    tk = os.path.join(snap, "tests", "TestKit.java")
    gate = os.path.join(snap, "tests", "SignatureConformanceTest.java")
    if include_gate and os.path.exists(gate):
        tests = [tk, gate]
    cmd = [JAVAC, "-cp", SVM_JAR, "-d", out] + sources + tests
    p = subprocess.run(cmd, capture_output=True, text=True)
    errors = Counter()
    for ln in (p.stdout + p.stderr).splitlines():
        m = re.match(r"(.+?):\d+: error: (.*)", ln)
        if m:
            path = os.path.relpath(m.group(1), snap)
            errors[path] += 1
    return p.returncode, errors, p.stdout + p.stderr


def run_gate(snap):
    out = os.path.join(bench.WORK, "sweep-classes")
    if not os.path.exists(os.path.join(out, "nsui", "tests", "SignatureConformanceTest.class")):
        return None
    p = subprocess.run([JAVA, "-XstartOnFirstThread", "--enable-native-access=ALL-UNNAMED",
                        "-cp", out, "nsui.tests.SignatureConformanceTest"],
                       capture_output=True, text=True)
    text = p.stdout + p.stderr
    mismatches = [ln.strip() for ln in text.splitlines() if "MISMATCH" in ln]
    result = [ln.strip() for ln in text.splitlines() if ln.startswith("RESULT")]
    return {"rc": p.returncode, "mismatches": mismatches, "result": result[-1] if result else "?"}


def main():
    ap = argparse.ArgumentParser(description="Sweep the generator across a point in history")
    ap.add_argument("--commit", required=True)
    ap.add_argument("--limit", type=int, default=0, help="cap the number of classes generated")
    ap.add_argument("--classes", help="comma-separated class list instead of the missing set")
    ap.add_argument("--overwrite", action="store_true",
                    help="with --classes: allow generating over a class the snapshot already has")
    ap.add_argument("--framework", dest="frameworks", action="append",
                    default=["AppKit", "QuartzCore", "Foundation", "Metal"])
    ap.add_argument("--inject-vocab", action="store_true",
                    help="copy today's Sig.java into the snapshot before generating")
    ap.add_argument("--gate", action="store_true", help="also run the snapshot's signature gate")
    ap.add_argument("--json", help="write the raw result JSON here")
    args = ap.parse_args()

    commit = subprocess.run(["git", "rev-parse", args.commit], cwd=REPO, capture_output=True,
                            text=True).stdout.strip()
    if not commit:
        ap.error("unknown commit " + args.commit)
    t0 = time.time()
    snap = snapshot_for(commit, args.inject_vocab)
    missing = classes_missing_at(snap)
    if args.classes:
        want = [c for c in args.classes.split(",") if c]
        if args.overwrite:
            classes = want
        else:
            skipped_over = [c for c in want if c not in missing]
            classes = [c for c in want if c in missing]
            if skipped_over:
                print("skipping %d class(es) already present at this commit: %s"
                      % (len(skipped_over), ", ".join(skipped_over)))
    else:
        classes = missing
    if args.limit:
        classes = classes[:args.limit]

    print("=== sweep %s (%s) ===" % (commit[:12], "vocab injected" if args.inject_vocab else "tree vocabulary"))
    print("missing wrappers at this commit: %d  generating: %d" % (len(classes_missing_at(snap)), len(classes)))
    gen_rc, summary = generate(snap, classes, args.frameworks)
    generated = sum(1 for ln in summary if ln.startswith("class "))
    skips = skip_histogram(summary)
    print("generator rc=%s  classes generated=%d  skip reasons=%d distinct" % (gen_rc, generated, len(skips)))

    compile_rc, errors, log = compile_snapshot(snap, include_gate=args.gate)
    gen_errors = {p: n for p, n in errors.items() if is_generated(os.path.join(snap, p))}
    pre_errors = {p: n for p, n in errors.items() if p not in gen_errors}
    print("compile rc=%s  errors in GENERATED files=%d (%d files)  elsewhere=%d (%d files)"
          % (compile_rc, sum(gen_errors.values()), len(gen_errors),
             sum(pre_errors.values()), len(pre_errors)))
    for path, n in sorted(gen_errors.items(), key=lambda kv: -kv[1])[:8]:
        print("   GEN  %-46s %d" % (path, n))
    for path, n in sorted(pre_errors.items(), key=lambda kv: -kv[1])[:3]:
        print("   pre  %-46s %d" % (path, n))
    gate = run_gate(snap) if args.gate else None
    if gate:
        print("gate rc=%s  %s  mismatches=%d" % (gate["rc"], gate["result"], len(gate["mismatches"])))
        for m in gate["mismatches"][:5]:
            print("   " + m[:120])

    print("\ntop skip reasons:")
    for reason, n in skips.most_common(10):
        print("   %4d  %s" % (n, reason[:110]))
    print("\nsweep took %.1fs" % (time.time() - t0))

    if args.json:
        json.dump({"commit": commit, "inject_vocab": args.inject_vocab, "classes": len(classes),
                   "generated": generated, "generator_rc": gen_rc,
                   "compile_rc": compile_rc, "compile_errors": errors.most_common(),
                   "generated_errors": sorted(gen_errors.items(), key=lambda kv: -kv[1]),
                   "skips": skips.most_common(), "gate": gate},
                  open(args.json, "w"), indent=2, sort_keys=True)
        print("wrote " + args.json)
    return 0


if __name__ == "__main__":
    sys.exit(main())
